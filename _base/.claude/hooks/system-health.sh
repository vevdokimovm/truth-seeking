#!/usr/bin/env bash
# system-health.sh — состояние ВСЕЙ системы при старте сессии в ЛЮБОЙ репе.
#
# Версия: 1.0.0 (2026-09-29)
#
# 🔴 ЗАКАЗ ВЛАДЕЛЬЦА 29.09.2026, дословно: «все скрпитпы гейты механизмы скилы
# генты должны быть ГЛОБАЛЬНЫ доступны всей системе!!! … чтобы при старте сесси
# в лдбой из реп они были доступны в актуальном поддерживающем состоянии».
#
# ЗАЧЕМ ХУК, А НЕ ПРАВИЛО И НЕ ЕЩЁ ОДИН ГЕЙТ.
# Гейты у системы уже есть, и они исправны. `repo_invariants.py --all` находит
# нарушения в реальных репах за полсекунды и написан ещё 02.09.2026 — но живёт
# в `base-repo/scripts/` и потому запускается только тогда, когда вахта работает
# в base-repo и вспомнила его позвать. Замер 29.09.2026: проверка находила
# 10 реп с нарушениями и не запускалась НИ РАЗУ.
#
# Это `ARCH-001` из `reports/architecture-defects.md`: система раздаёт знание
# копией (58 копий `_base/`, 1 ГБ, 45 309 файлов вместо 782), а копия не
# исполняется — она лишь лежит. Механизм должен существовать в ОДНОМ
# экземпляре и вызываться сам. Тот же приём, что вынес скиллы и агентов
# в `~/.claude/` 30.09.2026.
#
# ЧТО ДЕЛАЕТ. Зовёт два измерителя из базы ПО АБСОЛЮТНОМУ ПУТИ (не копией!)
# и печатает только то, что сломано:
#   · system_invariants.py — доведена ли работа до выпуска, пусты ли артефакты
#   · repo_invariants.py   — собраны ли репы правильно (сводка, без простыни)
#
# 🔴 ЗЕЛЁНОЕ МОЛЧИТ. Хук, печатающий «всё хорошо» при каждом старте, обучает
# пролистывать свой вывод, и в день, когда он скажет важное, его пролистают.
#
# 🔴 НИКОГДА НЕ РОНЯЕТ СЕССИЮ. Хук на старте, способный заблокировать работу,
# хуже отсутствующего: цена ложного срабатывания — потерянная сессия.
# Выход всегда 0, любая внутренняя ошибка проглатывается молча.
#
# 🔴 БЕЗ СЕТИ. Обе проверки локальные. Сеть 29.09.2026 падала трижды за день;
# старт сессии не может от неё зависеть.
#
# УСТАНОВКА: событие SessionStart в `~/.claude/settings.json`, раскатывается
# `scripts/sync_global_claude.py`. В project-local `.claude/` не кладётся
# намеренно — именно локальность и была дефектом.

# 🔴 ИМЕНА ПЕРЕМЕННЫХ — ТОЛЬКО ASCII (`PIT-202`, гейт `shell_ascii_check.py`).
# Первая редакция этого хука была написана с кириллическими именами и падала
# строкой `БАЗА=...: No such file or directory`: POSIX-шелл разбирает такое
# присваивание как ИМЯ КОМАНДЫ. Прозаический текст в комментариях и в выводе
# на русском — это другое, ограничение касается только идентификаторов.
set -uo pipefail   # без -e: падение измерителя не должно ронять хук

base="${BASE_REPO:-$HOME/repos/base-repo}"
[ -d "$base/scripts" ] || exit 0

# Не чаще раза в час на машину: старт сессии бывает частым (рестарты, /clear),
# а состояние системы за минуту не меняется. Полтора десятка секунд ожидания,
# размазанные по десяти стартам подряд, — это тот самый налог, из-за которого
# механизмы отключают.
stamp="${TMPDIR:-/tmp}/claude-system-health.stamp"
if [ -f "$stamp" ]; then
  now=$(date +%s)
  then_=$(stat -f %m "$stamp" 2>/dev/null || echo 0)
  [ $((now - then_)) -lt 3600 ] && exit 0
fi
: > "$stamp" 2>/dev/null || true

out=""

system="$(python3 "$base/scripts/system_invariants.py" --краткий 2>/dev/null || true)"
[ -n "$system" ] && out="$system"

# Из отчёта по репам берём только итоговую строку: полная простыня на старте
# сессии — это стена текста, которую не читают.
repos="$(python3 "$base/scripts/repo_invariants.py" --all 2>/dev/null \
         | grep -E '^ИТОГ:' | grep -vE 'с нарушениями 0' || true)"
if [ -n "$repos" ]; then
  out="${out:+$out
}🔴 R-правила · ${repos#ИТОГ: }
   разбор: python3 $base/scripts/repo_invariants.py --all"
fi

[ -n "$out" ] || exit 0

echo "🔴 СОСТОЯНИЕ СИСТЕМЫ — проверено при старте, не вручную:"
echo "$out"
exit 0
