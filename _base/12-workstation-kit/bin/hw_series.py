#!/usr/bin/env python3
"""hw_series.py — ряд замеров железа: что изнашивается и что изнашивает быстрее.

🔴 ЗАКАЗ ВЛАДЕЛЬЦА 30.09.2026, дословно: *«из-за замера мы можем отслеживать
состояние изменение метала. и выяснить что его убивает сильнее всего. давай
отслеживать регулярно»*.

ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ — граница с соседями по киту, чтобы не развести дубль:

    machine_probe.py    СНИМОК сейчас: нагрузка, память, диск, пороги
    firmware_probe.py   версии прошивок — то, что меняется раз в год
    HARDWARE.md         ПАСПОРТ: параметры, оценка узлов, протокол замера
    hw_series.py (это)  РЯД: одна строка на замер, append-only, и ПРОИЗВОДНЫЕ

🔴 ПОЧЕМУ РЯД, А НЕ СНИМОК. Снимок отвечает «износ 112 %», и по нему нельзя
решить ничего: 112 % — это много или это норма для семи лет? Две точки
отвечают «плюс 33 ТБ за 28 дней, то есть 1.18 ТБ в сутки при бытовой норме
10-30 ГБ» — и вот это уже решение. Ровно так дефект и был найден 30.09.2026:
сравнением с отчётом от 02.09, а не осмотром.

ЧТО СЧИТАЕТСЯ ПРОИЗВОДНЫМ (для этого и нужен ряд)
  · ТБ записи в сутки — главный расходник: SSD распаян, замене не подлежит;
  · процент износа в месяц и оценка, когда кончится резерв блоков;
  · циклов батареи в сутки и потеря ёмкости в месяц;
  · растёт ли своп и вытеснения — то есть ЧТО ИМЕННО жжёт диск.

🔴 ЧЕГО ЭТА ПРОГРАММА НЕ ВИДИТ
  · ПРИЧИНУ записи. SMART хранит сумму, а не историю: по нему нельзя сказать,
    чем именно записаны терабайты. Своп — главный подозреваемый по косвенным
    (растёт вместе с записью), но это корреляция, не доказательство.
  · износ между замерами. Ряд из редких точек усредняет: пик в один день
    и ровная неделя дают одно число.
  · температуру под нагрузкой: `powermetrics` требует прав администратора,
    и просить их программа не будет (`107`: никаких запросов админ-прав).
  · СЕТЬ. В ряду её нет намеренно и не появится: внешний адрес, шлюз, имя
    Wi-Fi, статус туннеля не собираются ни при каком поводе (`107`).

ЗАПУСК
    hw_series.py                 замерить и дописать строку (раз в сутки)
    hw_series.py --show          показать ряд и производные, ничего не писать
    hw_series.py --force         дописать, даже если за сегодня строка есть
    hw_series.py --selftest
"""
from __future__ import annotations

import argparse
import datetime as dt
import re
import subprocess
import sys
from pathlib import Path

КИТ = Path(__file__).resolve().parent.parent
РЯД = КИТ / "observations" / "hw-series.tsv"

ПОЛЯ = ("дата", "аптайм_сут", "ssd_износ_проц", "записано_ТБ", "прочитано_ТБ",
        "часов_включения", "включений", "аварийных_выключений", "резерв_блоков_проц",
        "ssd_темп_C", "батарея_циклов", "батарея_мАч", "батарея_проект_мАч",
        "батарея_износ_проц", "батарея_темп_C", "своп_занято_МБ", "своп_всего_МБ",
        "вытеснений", "диск_свободно_ГБ", "диск_занято_проц",
        "load1", "load5", "load15", "лимит_цпу_проц", "бэкапов_TM")


def вывод(команда: list[str]) -> str:
    """stdout команды или пустая строка. Пустая строка честно значит «не узнал»."""
    try:
        r = subprocess.run(команда, capture_output=True, text=True, timeout=60)
        return r.stdout
    except (OSError, subprocess.SubprocessError):
        return ""


def число(текст: str, шаблон: str, множитель: float = 1.0) -> str:
    """Первое число по шаблону, иначе пустая клетка — НЕ ноль.

    🔴 Ноль вместо «не узнал» — тот самый дефект, который система уже
    ловила дважды (`ARCH-003`): законная пустота, выданная за ответ.
    """
    m = re.search(шаблон, текст)
    if not m:
        return ""
    очищено = m.group(1).replace(",", "").replace(" ", "").replace(" ", "")
    try:
        return f"{float(очищено) * множитель:g}"
    except ValueError:
        return ""


def снять() -> dict[str, str]:
    """Полный срез железа на сейчас. Пустая клетка = не узнали."""
    з: dict[str, str] = {п: "" for п in ПОЛЯ}
    з["дата"] = dt.date.today().isoformat()

    up = вывод(["uptime"])
    з["аптайм_сут"] = число(up, r"up\s+(\d+)\s+day")
    m = re.search(r"load averages?:\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)", up)
    if m:
        з["load1"], з["load5"], з["load15"] = m.group(1), m.group(2), m.group(3)

    smart = вывод(["smartctl", "-a", "/dev/disk0"])
    з["ssd_износ_проц"] = число(smart, r"Percentage Used:\s+(\d+)%")
    з["резерв_блоков_проц"] = число(smart, r"Available Spare:\s+(\d+)%")
    з["ssd_темп_C"] = число(smart, r"Temperature:\s+(\d+) Celsius")
    з["часов_включения"] = число(smart, r"Power On Hours:\s+([\d,]+)")
    з["включений"] = число(smart, r"Power Cycles:\s+([\d,]+)")
    з["аварийных_выключений"] = число(smart, r"Unsafe Shutdowns:\s+([\d,]+)")
    # 🔴 Data Units = 1000 блоков по 512 байт. В ТБ: units * 512000 / 1e12.
    з["записано_ТБ"] = число(smart, r"Data Units Written:\s+([\d,]+)", 512e3 / 1e12)
    з["прочитано_ТБ"] = число(smart, r"Data Units Read:\s+([\d,]+)", 512e3 / 1e12)

    bat = вывод(["ioreg", "-rn", "AppleSmartBattery"])
    з["батарея_циклов"] = число(bat, r'"CycleCount" = (\d+)')
    з["батарея_мАч"] = число(bat, r'"AppleRawMaxCapacity" = (\d+)')
    з["батарея_проект_мАч"] = число(bat, r'"DesignCapacity" = (\d+)')
    з["батарея_темп_C"] = число(bat, r'"Temperature" = (\d+)', 0.01)
    if з["батарея_мАч"] and з["батарея_проект_мАч"]:
        износ = 100 - float(з["батарея_мАч"]) / float(з["батарея_проект_мАч"]) * 100
        з["батарея_износ_проц"] = f"{износ:.1f}"

    своп = вывод(["sysctl", "vm.swapusage"])
    з["своп_всего_МБ"] = число(своп, r"total = ([\d.]+)M")
    з["своп_занято_МБ"] = число(своп, r"used = ([\d.]+)M")
    з["вытеснений"] = число(вывод(["vm_stat"]), r"Pageouts:\s+(\d+)")

    df = вывод(["df", "-g", "/"]).splitlines()
    if len(df) > 1:
        к = df[1].split()
        if len(к) > 4:
            з["диск_свободно_ГБ"] = к[3]
            з["диск_занято_проц"] = к[4].rstrip("%")

    з["лимит_цпу_проц"] = число(вывод(["pmset", "-g", "therm"]),
                                r"CPU_Speed_Limit\s*=\s*(\d+)")

    tm = вывод(["tmutil", "listbackups"])
    з["бэкапов_TM"] = "0" if "No machine directory" in tm or not tm.strip() else str(
        len([с for с in tm.splitlines() if с.strip()]))
    return з


def прочитать_ряд() -> list[dict[str, str]]:
    if not РЯД.is_file():
        return []
    строки = [с for с in РЯД.read_text(encoding="utf-8").splitlines() if с.strip()]
    if not строки:
        return []
    шапка = строки[0].split("\t")
    return [dict(zip(шапка, с.split("\t"))) for с in строки[1:]]


def дописать(з: dict[str, str]) -> None:
    РЯД.parent.mkdir(parents=True, exist_ok=True)
    новый = not РЯД.is_file()
    with РЯД.open("a", encoding="utf-8") as ф:
        if новый:
            ф.write("\t".join(ПОЛЯ) + "\n")
        ф.write("\t".join(з.get(п, "") for п in ПОЛЯ) + "\n")


def дельта(а: dict[str, str], б: dict[str, str], поле: str) -> float | None:
    """Разница поля между двумя замерами, None — если хоть одна клетка пуста."""
    if not а.get(поле) or not б.get(поле):
        return None
    try:
        return float(б[поле]) - float(а[поле])
    except ValueError:
        return None


def суток(а: dict[str, str], б: dict[str, str]) -> int | None:
    try:
        return (dt.date.fromisoformat(б["дата"]) - dt.date.fromisoformat(а["дата"])).days
    except (KeyError, ValueError):
        return None


def производные(ряд: list[dict[str, str]]) -> list[str]:
    """Что изнашивается и что изнашивает — по двум последним замерам."""
    если_мало = ["🟡 в ряду меньше двух замеров — производные не считаются. "
                 "Одна точка не говорит ничего о скорости износа."]
    if len(ряд) < 2:
        return если_мало
    а, б = ряд[-2], ряд[-1]
    д = суток(а, б)
    if not д:
        return ["🟡 два замера в один день — производные не считаются"]

    из_: list[str] = [f"между замерами {а['дата']} → {б['дата']}: {д} сут."]

    тб = дельта(а, б, "записано_ТБ")
    if тб is not None:
        в_сутки_гб = тб * 1000 / д
        оценка = "🟢" if в_сутки_гб < 30 else "🟡" if в_сутки_гб < 200 else "🔴"
        из_.append(f"{оценка} запись: +{тб:.1f} ТБ, это {в_сутки_гб:.0f} ГБ/сут "
                   f"(бытовая норма 10-30 ГБ/сут)")
        часы = дельта(а, б, "часов_включения")
        if часы and часы > 0:
            из_.append(f"   в час работы: {тб * 1000 / часы:.0f} ГБ/ч "
                       f"(норма 1-3 ГБ/ч), часов работы за период: {часы:.0f}")

    износ = дельта(а, б, "ssd_износ_проц")
    if износ is not None:
        в_месяц = износ * 30 / д
        из_.append(f"{'🔴' if в_месяц >= 3 else '🟡' if в_месяц >= 1 else '🟢'} "
                   f"износ SSD: +{износ:g} п.п., это {в_месяц:.1f} п.п./месяц")
    резерв = дельта(а, б, "резерв_блоков_проц")
    if резерв is not None:
        из_.append("🟢 резерв блоков не тронут — отказа не начиналось" if резерв == 0
                   else f"🔴 РЕЗЕРВ БЛОКОВ ПОШЁЛ ВНИЗ на {abs(резерв):g} п.п. — "
                        f"это предвестник отказа, а не пробег")

    циклы = дельта(а, б, "батарея_циклов")
    if циклы is not None:
        из_.append(f"батарея: +{циклы:g} циклов ({циклы / д:.2f}/сут)")
    ёмкость = дельта(а, б, "батарея_износ_проц")
    if ёмкость is not None:
        из_.append(f"износ батареи: +{ёмкость:.1f} п.п. за период")

    место = дельта(а, б, "диск_свободно_ГБ")
    if место is not None:
        из_.append(f"{'🔴' if место < -20 else '🟡' if место < 0 else '🟢'} "
                   f"свободного места: {место:+.0f} ГБ")
    вытеснения = дельта(а, б, "вытеснений")
    if вытеснения is not None and вытеснения > 0:
        из_.append(f"вытеснений страниц: +{вытеснения:,.0f} — каждое это запись "
                   f"на диск, и это главный подозреваемый по записи")

    аварии = дельта(а, б, "аварийных_выключений")
    if аварии:
        из_.append(f"🔴 аварийных выключений: +{аварии:g} — машина гасла жёстко")
    return из_


def selftest() -> int:
    """Пустая клетка обязана оставаться пустой, а не превращаться в ноль."""
    assert число("нет числа", r"(\d+)%") == "", "не найдено обязано дать пустоту"
    assert число("Percentage Used: 112%", r"Percentage Used:\s+(\d+)%") == "112"
    тб = число("Data Units Written: 1,933,048,711", r"Written:\s+([\d,]+)", 512e3 / 1e12)
    assert abs(float(тб) - 989.72) < 0.01, f"перевод в ТБ сломан: {тб}"
    а = {"дата": "2026-09-02", "записано_ТБ": "956", "ssd_износ_проц": "108",
         "резерв_блоков_проц": "100", "часов_включения": "7058"}
    б = {"дата": "2026-09-30", "записано_ТБ": "989", "ssd_износ_проц": "112",
         "резерв_блоков_проц": "100", "часов_включения": "7300"}
    строки = производные([а, б])
    текст = "\n".join(строки)
    assert "1179 ГБ/сут" in текст, f"темп записи посчитан неверно:\n{текст}"
    assert "резерв блоков не тронут" in текст, "резерв разобран неверно"
    assert дельта(а, {"дата": "x"}, "записано_ТБ") is None, "пустота обязана давать None"
    assert производные([а])[0].startswith("🟡"), "одна точка не даёт производных"
    падение = производные([а | {"резерв_блоков_проц": "100"},
                           б | {"резерв_блоков_проц": "97"}])
    assert any("РЕЗЕРВ БЛОКОВ ПОШЁЛ ВНИЗ" in с for с in падение), "падение резерва не поймано"
    print("🟢 канарейка ряда: не найденное остаётся пустым и не становится нулём, "
          "темп записи считается верно, падение резерва ловится")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--show", action="store_true", help="показать ряд, не дописывая")
    ap.add_argument("--force", action="store_true", help="дописать вторую строку за день")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()

    ряд = прочитать_ряд()
    if not a.show:
        сегодня = dt.date.today().isoformat()
        если_есть = [с for с in ряд if с.get("дата") == сегодня]
        if если_есть and not a.force:
            print(f"🟡 за {сегодня} строка уже есть — не дописываю. "
                  f"Нужна вторая: --force")
        else:
            з = снять()
            пустых = sum(1 for п in ПОЛЯ if not з.get(п))
            дописать(з)
            ряд = прочитать_ряд()
            print(f"🟢 замер дописан: {РЯД.relative_to(КИТ.parent)} · "
                  f"полей {len(ПОЛЯ)}, не узнано {пустых}")

    if not ряд:
        print("🔴 ряд пуст")
        return 1

    п = ряд[-1]
    print(f"\n── состояние на {п['дата']} ──")
    print(f"SSD      износ {п['ssd_износ_проц'] or '?'} % · резерв блоков "
          f"{п['резерв_блоков_проц'] or '?'} % · записано {п['записано_ТБ'] or '?'} ТБ · "
          f"{п['ssd_темп_C'] or '?'} °C")
    print(f"Батарея  циклов {п['батарея_циклов'] or '?'} · износ "
          f"{п['батарея_износ_проц'] or '?'} % · {п['батарея_мАч'] or '?'} из "
          f"{п['батарея_проект_мАч'] or '?'} мАч")
    выт = п["вытеснений"]
    выт = f"{int(float(выт)):,}".replace(",", " ") if выт else "?"
    print(f"Память   своп {п['своп_занято_МБ'] or '?'} из {п['своп_всего_МБ'] or '?'} МБ · "
          f"вытеснений {выт}")
    print(f"Диск     свободно {п['диск_свободно_ГБ'] or '?'} ГБ · занято "
          f"{п['диск_занято_проц'] or '?'} % · копий Time Machine {п['бэкапов_TM'] or '?'}")
    print(f"Нагрузка load {п['load1'] or '?'}/{п['load5'] or '?'}/{п['load15'] or '?'} · "
          f"лимит ЦП {п['лимит_цпу_проц'] or '?'} %")

    print(f"\n── что изнашивается (замеров в ряду: {len(ряд)}) ──")
    for строка in производные(ряд):
        print(строка)
    print("\n🔴 ПРИЧИНУ записи этот ряд не доказывает: SMART хранит сумму, "
          "а не историю. Своп — подозреваемый по косвенным, не улика.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
