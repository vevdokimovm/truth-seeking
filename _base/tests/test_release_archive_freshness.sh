#!/usr/bin/env bash
# =============================================================================
# test_release_archive_freshness.sh — архив релиза обязан совпадать с рабочей
# копией, и постусловие батча обязано это ловить.
#
# 🔴 ПОВОД — ВЫПУСК `legal-knowledge-base` v2.68.0, 26.09.2026. `close_batch.py`
# паковал архив четвёртым шагом, а шаг «состояние на закрытие» после него
# переписывал `STATE-NOW.md` и дописывал указатель в `WATCHLOG.md` §0. Значит
# архив расходился с рабочей копией НА КАЖДОМ БАТЧЕ без исключения, и
# `publish.py` штатно его браковал: один скрипт ритуала производил артефакт,
# который второй скрипт того же ритуала обязан был забраковать.
#
# Дефект держался, потому что смотрели на код возврата: упаковщик отвечал
# нулём, архив существовал, постусловия его находили. Третий повтор класса
# `PIT-J` (вред на стыке двух верных механизмов), и все три — этот же стык.
# По правилу `PITFALLS.md` третий повтор закрывается механической проверкой.
#
# ЧТО ПРОВЕРЯЕТСЯ — РАЗЛИЧЕНИЕ двух исходов, а не один «хороший»:
#   1. архив собран последним действием → проверка молчит;
#   2. файл репы правлен после упаковки → проверка возражает.
#
# Мёртвая канарейка (всегда «молчит») прошла бы только первый кейс — поэтому
# второй и есть тест, а первый защищает от обратного: проверки, которая ругает
# всё подряд и потому игнорируется.
#
# ГЕРМЕТИЧНОСТЬ. Игрушечная репа во временном каталоге, свой каталог артефактов
# через `BASE_ARTIFACTS`. Ни сети, ни настоящих реп, ни записи в артефакты базы.
#
# ЗАПУСК:  bash tests/test_release_archive_freshness.sh    (из корня base-repo)
# =============================================================================
set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"

printf '\n\033[1m── свежесть архива релиза ──\033[0m\n'

if python3 "$ROOT/tests/bin/archive_freshness_canary.py"; then
    printf '\n  пройдено: 2\n  падений:  0\n\n'
    exit 0
fi

printf '\n  🔴 постусловие батча больше не отличает свежий архив от устаревшего.\n'
printf '     Чинить, а не ослаблять: разбор — PIT-J в reports/incidents/PITFALLS.md\n\n'
exit 1
