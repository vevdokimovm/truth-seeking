#!/usr/bin/env python3
"""naming_fix.py — привести имена к стандарту и переписать ВСЕ ссылки на них.

🔴 ЗАКАЗ ВЛАДЕЛЬЦА 29.09.2026: «да все супер делай. ссылки естесвтенно надо
тоже править правильно говоришь». Правило — `01-repo-standard.md` §1,
перечисление нарушений — `naming_check.py` (он же и остаётся гейтом).

ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ СКРИПТ, А НЕ КЛЮЧ `--fix` У ПРОВЕРКИ.
Переименование документа — не косметика: имя есть АДРЕС. На `report-types.md`
ссылаются из README и гейтов, на `98-readme-standard.md` — по номеру. Файл,
переименованный без правки ссылок, не «слегка неаккуратен» — он потерян для
всех, кто шёл по ссылке. Поэтому переименование и проверка разведены:
проверка зелёная всегда безопасна, а эта операция — нет.

ДВА ВИДА РАБОТЫ, И ОНИ НАМЕРЕННО РАЗДЕЛЕНЫ:
  · механика  — подчёркивание → дефис, точка в основе имени → дефис;
                выводится правилом, считается машиной;
  · суждение  — транслитерация → осмысленное английское имя; машина не знает,
                что `put-s-iisusom-khristom` это `walk-with-christ`.
                Такие имена перечислены в `ПЕРЕВОД` поимённо, и каждое —
                решение вахты, а не результат алгоритма (`71` §7г-бис).

🔴 НЕДЕСТРУКТИВНО ПО ПОСТРОЕНИЮ (`00-CLAUDE-STOP` «Третье»):
  · существующий файл никогда не перезаписывается — цель занята, значит стоп;
  · `git mv`, чтобы история файла не оборвалась;
  · после правки ссылок печатается остаток — упоминания СТАРОЙ основы имени
    без расширения, которые заменять было бы опасно (они могли бы оказаться
    именем переменной), — чтобы их посмотрел человек.

ЗАПУСК
    naming_fix.py --dry      что будет переименовано и сколько ссылок затронуто
    naming_fix.py            сделать
    naming_fix.py --selftest
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

БАЗА = Path(__file__).resolve().parent.parent
НЕ_СМОТРИМ = {".git", "_base", "__pycache__", ".venv", "node_modules",
              ".pytest_cache", ".ipynb_checkpoints", "__MACOSX"}
# Где ИЩЕМ ссылки — широко: на документ ссылаются и из кода, и из конфигов.
ТЕКСТ = {".md", ".py", ".sh", ".json", ".yml", ".yaml", ".txt", ".toml", ".cfg"}
# 🔴 Что ПЕРЕИМЕНОВЫВАЕМ — только документы. Поймано сухим прогоном 29.09.2026:
# инструмент собрался сделать `import_dedup.py` → `import-dedup.py`, то есть
# оборвать каждый `from ... import` и каждый вызов скрипта в хуках и гейтах.
# Стандарт (§1в.2) это прямо оговаривает: у файлов кода действует PEP 8
# с подчёркиванием, и он сильнее правила нейминга документов. Инструмент
# правила не знал — множество «где ищем» было принято за «что правим».
ПЕРЕИМЕНОВЫВАЕМ = {".md"}

# 🔴 СУЖДЕНИЕ, НЕ АЛГОРИТМ. Каждое имя переведено вахтой по смыслу документа,
# а не транслитератором: `ucheba-obrazovanie` — это «образование», а не
# «ucheba-education». Даты вынесены в начало там, где документ описывает
# событие: по §1б дата и есть порядок, и она должна стоять первой.
# 🔴 КЛЮЧИ СОБИРАЮТСЯ ИЗ КУСКОВ, А НЕ ПИШУТСЯ ЛИТЕРАЛОМ — и это не причуда.
# 29.09.2026 первый боевой прогон переписал ЭТУ ЖЕ таблицу: старые имена
# стояли здесь строками, проход правки ссылок честно счёл их ссылками
# и заменил на новые. Таблица стала тождественной («walk-with-christ.md»:
# «walk-with-christ.md»), то есть инструмент уничтожил собственные данные,
# отработав при этом правильно. Два слоя защиты: файл исключён из правки
# (`САМ_СЕБЕ`) и ключ не совпадает ни с одной строкой на диске.
_ = "".join  # короткая сборка, чтобы литерал не встречался целиком


def _имя(*куски: str) -> str:
    return "-".join(куски) + ".md"


ПЕРЕВОД = {
    "00-" + "NEPRONUMEROVANNYE.md": "00-UNNUMBERED.md",
    _имя("kak", "polzovatsya", "instruktsiyami"): "how-to-use-instructions.md",
    _имя("kontekst", "vasiliy", "edinyy"): "context-vasilii-unified.md",
    _имя("pamyat", "dlya", "vsekh", "akkauntov"): "memory-for-all-accounts.md",
    _имя("put", "s", "iisusom", "khristom"): "walk-with-christ.md",
    _имя("ucheba", "obrazovanie"): "education.md",
    _имя("OPYT", "vahta", "i", "provaly"): "lessons-watch-and-failures.md",
    _имя("dota", "zavisaniya", "diagnoz", "2026", "09", "05"):
        "2026-09-05-dota-freezes-diagnosis.md",
    _имя("nochnoe", "otklyuchenie", "2026", "09", "06"):
        "2026-09-06-night-shutdown.md",
    _имя("claude", "code", "dlya", "sistemy", "iz", "41", "repozitoriya",
         "bazy", "znaniy", "anal"): "claude-code-for-41-repo-system-analysis.md",
    _имя("pitfalls", "bez", "mekhanizma"): "pitfalls-without-mechanism.md",
    _имя("2026", "07", "08", "upakovka", "arkhivov", "v", "repozitorii"):
        "2026-07-08-packing-archives-into-repos.md",
    _имя("2026", "07", "18", "cowork", "avtomatizatsiya", "i", "metodichki"):
        "2026-07-18-cowork-automation-and-guides.md",
    _имя("2026", "08", "20", "sinkhronizatsiya", "vsekh", "repozitoriev"):
        "2026-08-20-syncing-all-repos.md",
    _имя("2026", "09", "15", "poterya", "originalov", "za", "sluzhebkami"):
        "2026-09-15-originals-lost-behind-notes.md",
}

# 🔴 Файлы, где имена лежат КАК ДАННЫЕ, а не как ссылки. Правка здесь —
# порча таблицы и фикстур тестов, а не обновление ссылки. Инструмент,
# способный переписать собственный вход, недоказуем: он отработает «успешно»
# и оставит другой результат, чем показал сухой прогон.
САМ_СЕБЕ = {"scripts/naming_fix.py", "scripts/naming_check.py"}


# 🔴 КАТАЛОГИ — отдельно от файлов: у каталога меняется не имя, а ПУТЬ, и
# ссылка на него встречается куском `17-manifest-aot/…`, а не целым именем.
# Найдено владельцем 29.09.2026: «почему там две папки с номером 00».
# `00-` зарезервирован стандартом под инфраструктуру (§1г.5), а разбор
# «Атаки титанов» — предметный материал; уезжает он, а не инфраструктура.
# 17 — первый свободный номер (заняты 00–16).
КАТАЛОГИ = {
    "17-manifest-aot": "17-manifest-aot",
}


def механическое(имя: str) -> str | None:
    """Новое имя по правилу, либо None — правило этого файла не касается."""
    основа, точка, расш = имя.rpartition(".")
    if not точка or f".{расш}" not in ПЕРЕИМЕНОВЫВАЕМ:
        return None
    ново = основа.replace("_", "-").replace(".", "-")
    return f"{ново}.{расш}" if ново != основа else None


def файлы(корень: Path):
    for п in корень.rglob("*"):
        if any(ч in НЕ_СМОТРИМ or (ч.startswith(".") and ч != ".")
               for ч in п.relative_to(корень).parts):
            continue
        if п.is_file():
            yield п


def план(корень: Path) -> list[tuple[Path, str, str]]:
    """[(путь, старое имя, новое имя)] — сначала суждение, потом механика."""
    из = []
    for п in sorted(файлы(корень)):
        ново = ПЕРЕВОД.get(п.name) or механическое(п.name)
        if ново and ново != п.name:
            из.append((п, п.name, ново))
    return из


def переписать_ссылки(корень: Path, замены: dict[str, str], сухо: bool) -> tuple[int, int]:
    """Возвращает (файлов правлено, ссылок заменено)."""
    if not замены:
        return 0, 0
    # 🔴 Заменяется ТОЛЬКО полное имя с расширением. Замена основы без
    # расширения задела бы совпадающие идентификаторы в коде, а это правка
    # вслепую в чужом смысле. Остаток упоминаний печатается человеку.
    шаблон = re.compile("|".join(re.escape(с) for с in sorted(замены, key=len, reverse=True)))
    правлено = ссылок = 0
    for п in sorted(файлы(корень)):
        if п.suffix not in ТЕКСТ or str(п.relative_to(корень)) in САМ_СЕБЕ:
            continue
        try:
            текст = п.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        новый, n = шаблон.subn(lambda m: замены[m.group(0)], текст)
        if n:
            правлено += 1
            ссылок += n
            if not сухо:
                п.write_text(новый, encoding="utf-8")
    return правлено, ссылок


def остаток(корень: Path, основы: list[str]) -> list[str]:
    """Упоминания СТАРОЙ основы без расширения — на глаза человеку."""
    найдено = []
    if not основы:
        return найдено
    шаблон = re.compile("|".join(re.escape(о) for о in основы))
    for п in sorted(файлы(корень)):
        if п.suffix not in ТЕКСТ:
            continue
        try:
            текст = п.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        for m in шаблон.finditer(текст):
            найдено.append(f"{п.relative_to(корень)}: …{текст[max(0, m.start()-30):m.end()+20]}…")
    return найдено


def переименовать(п: Path, ново: str) -> str | None:
    """None — успех, иначе причина отказа."""
    цель = п.with_name(ново)
    if цель.exists():
        return f"цель уже занята: {цель.name}"
    r = subprocess.run(["git", "-C", str(БАЗА), "mv", str(п), str(цель)],
                       capture_output=True, text=True)
    if r.returncode != 0:
        try:
            п.rename(цель)          # файл вне git — переименовываем как есть
        except OSError as e:
            return str(e)
    return None


def selftest() -> int:
    п = "_"   # фикстуры собираются, а не пишутся: см. комментарий у ПЕРЕВОД
    assert механическое(f"report{п}types.md") == "report-types.md"
    assert механическое("fjord.prompt.md") == "fjord-prompt.md"
    assert механическое(f"CHANGELOG{п}TEMPLATE.md") == "CHANGELOG-TEMPLATE.md"
    assert механическое("already-fine.md") is None
    assert механическое("photo.jpg") is None, "нетекстовые не трогаем"
    assert механическое(f"import{п}dedup.py") is None, "код живёт по PEP 8, §1в.2"
    assert механическое(f"sync{п}base.sh") is None, "скрипты не переименовываем"
    ключ = "-".join(("put", "s", "iisusom", "khristom")) + ".md"
    assert ПЕРЕВОД[ключ] == "walk-with-christ.md", "таблица перевода не тождественна"
    assert not any(к == з for к, з in ПЕРЕВОД.items()), \
        "ключ, равный значению, значит таблицу переписал собственный проход"
    assert len(set(ПЕРЕВОД.values())) == len(ПЕРЕВОД), "переводы не должны совпадать"
    assert "scripts/naming_fix.py" in САМ_СЕБЕ, "инструмент не правит собственный вход"
    print("🟢 selftest: механика считается правилом, перевод задан поимённо, "
          "расширение сохраняется, нетекстовые файлы не трогаются")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()

    работа = план(БАЗА)
    if not работа:
        print("🟢 переименовывать нечего — имена уже по стандарту")
        return 0

    суждение = [(п, с, н) for п, с, н in работа if с in ПЕРЕВОД]
    механика = [(п, с, н) for п, с, н in работа if с not in ПЕРЕВОД]
    print(f"к переименованию: {len(работа)} "
          f"(суждение — {len(суждение)}, механика — {len(механика)})\n")
    for заголовок, часть in (("СУЖДЕНИЕ — перевод имени", суждение),
                             ("МЕХАНИКА — по правилу", механика)):
        print(f"── {заголовок}: {len(часть)}")
        for п, с, н in часть[:200]:
            print(f"   {п.relative_to(БАЗА).parent}/  {с}  →  {н}")
        print()

    каталоги = {с: н for с, н in КАТАЛОГИ.items() if (БАЗА / с).is_dir()}
    if каталоги:
        print(f"── КАТАЛОГИ — номер занят дважды: {len(каталоги)}")
        for с, н in каталоги.items():
            print(f"   {с}/  →  {н}/")
        print()

    замены = {с: н for _, с, н in работа} | каталоги
    правлено, ссылок = переписать_ссылки(БАЗА, замены, сухо=True)
    print(f"ссылок будет переписано: {ссылок} в {правлено} файлах")

    if a.dry:
        print("\n🟡 --dry: ничего не изменено")
        return 0

    # 🔴 Порядок обязателен: сначала ссылки, потом файлы. Если оборвёмся
    # посередине, ссылки будут указывать на будущее имя — это чинится вторым
    # прогоном. Обратный порядок оставил бы файлы без ссылок и без следа.
    правлено, ссылок = переписать_ссылки(БАЗА, замены, сухо=False)
    print(f"\n🟢 ссылок переписано: {ссылок} в {правлено} файлах")

    сделано, отказы = 0, []
    for п, с, н in работа:
        причина = переименовать(п, н)
        if причина:
            отказы.append(f"{с}: {причина}")
        else:
            сделано += 1
    # Каталоги — после файлов: пути внутри них уже не меняются, а `git mv`
    # каталога переносит всё содержимое одним ходом.
    for с, н in каталоги.items():
        причина = переименовать(БАЗА / с, н)
        if причина:
            отказы.append(f"{с}/: {причина}")
        else:
            сделано += 1
            print(f"🟢 каталог: {с}/ → {н}/")
    print(f"🟢 переименовано: {сделано} из {len(работа) + len(каталоги)}")
    for о in отказы:
        print(f"🔴 не переименовано — {о}")

    хвост = остаток(БАЗА, [с.rsplit(".", 1)[0] for _, с, _ in работа])
    if хвост:
        print(f"\n🟡 упоминаний старой основы БЕЗ расширения: {len(хвост)} — "
              f"заменять вслепую нельзя, смотреть глазами:")
        for строка in хвост[:25]:
            print(f"   · {строка}")
    return 1 if отказы else 0


if __name__ == "__main__":
    sys.exit(main())
