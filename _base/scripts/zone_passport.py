#!/usr/bin/env python3
"""zone_passport.py — паспорт защищённости зон системы: NN/100 по каждой.

🔴 ЗАКАЗ ВЛАДЕЛЬЦА 30.09.2026, дословно: «введи концепцию паспорта качество
также на механизма насколько правила протколы документация системы реально
в работе реально созданы механизмы контроля правил. из 100. и тоже гейт 90+».

Повод — его же вопрос того же дня: что будет с системой, если исполнителем
станет СЛАБАЯ модель, которая ошибается консистентно и молчит. Ответ на такой
вопрос упирается в число, которого не было: какая доля системы защищена
механизмом, а какая держится на том, что кто-то вспомнит проверить.

ЧТО СЧИТАЕТСЯ — ПЯТЬ СЛАГАЕМЫХ, ВСЕ ИЗМЕРИМЫ С ДИСКА

    25  исполнитель существует   файл механизма лежит на диске
    25  включён в конвейер       его зовёт гейт, ритуал, хук или pre-commit
    20  канарейка                у механизма есть --selftest
    15  охват назван числом      печатает знаменатель («X из Y», «проверено N»)
    15  слепое пятно объявлено   сам говорит, чего не видит

🔴 ПОЧЕМУ ИМЕННО «ВКЛЮЧЁН В КОНВЕЙЕР» СТОИТ ТАК ЖЕ ДОРОГО, КАК САМО
СУЩЕСТВОВАНИЕ. Скрипт, который никто не зовёт автоматически, — это правило,
записанное другими буквами: исполнитель у него по-прежнему «человек вспомнит».
В системе это уже стоило месяца молчания (`PIT-G`, повтор 24: обойдя ритуал,
выключили проверку на собственное залипание).

🔴 ЧЕГО ЭТА ПРОВЕРКА НЕ ВИДИТ — и это важнее списка выше:
  · ВЕРЕН ли механизм. Скрипт может исправно проверять не то, что нужно;
    паспорт поставит ему полные 100. Это verification, не validation —
    та же граница, что у `gate_monitor.py`.
  · достаточность охвата. «Проверено 7 файлов» печатается одинаково и когда
    файлов семь, и когда их семьсот, а видит гейт семь (`ARCH-005`).
  · три из пяти слагаемых — ПРОКСИ по тексту файла (канарейка, знаменатель,
    слепое пятно ищутся подстрокой). Переименуют приём — прокси перестанет
    попадать, и число уедет вниз при неизменной защите.

🔴 ПОРОГ НЕ БЛОКИРУЕТ СЕГОДНЯ, И ЭТО НАМЕРЕННО. Тот же ход, что у
`pit_gate_coverage.py`: жёсткий гейт в день внедрения запретил бы выпуск,
когда паспорт только заведён, — и его выключили бы вместо того, чтобы растить
защиту. Порог живёт ключом `--gate NN` и поднимается по мере роста числа.
Antihrupkost' растёт, а не объявляется.

ЗАПУСК
    zone_passport.py                 таблица зон и общий балл
    zone_passport.py --verbose       по каждой зоне: чего не хватает
    zone_passport.py --gate 90       код возврата 1, если общий балл ниже
    zone_passport.py --selftest
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

БАЗА = Path(__file__).resolve().parent.parent
ПАСПОРТ = БАЗА / "00-infrastructure" / "113-zone-protection-passport.md"

# Где ищутся объявленные механизмы. Порядок не важен: имя уникально.
КАТАЛОГИ = ("scripts", ".claude/hooks", ".githooks", "templates")

# Кто считается конвейером: файлы, вызов из которых означает «зовётся сам».
КОНВЕЙЕР = ("scripts/revision_check.py", "scripts/close_batch.py",
            "scripts/publish.py", "scripts/pack_release.py",
            "scripts/bump_repo.py", "templates/pre-commit")

ИМЯ_МЕХАНИЗМА = re.compile(r"`([A-Za-z0-9_./-]+\.(?:py|sh))`")

# Прокси-признаки. Список намеренно широкий: узкий дал бы ложный ноль.
ПРИЗНАК_КАНАРЕЙКИ = ("--selftest", "def selftest", "канарейк")
ПРИЗНАК_ЗНАМЕНАТЕЛЯ = ("из {", " из ", "проверено", "всего:", "охват")
ПРИЗНАК_СЛЕПОГО = ("НЕ ловит", "не видит", "слепое пятно", "НЕ покрыт",
                   "чего не", "не поймает", "не проверяет")

ВЕС = {"существует": 25, "конвейер": 25, "канарейка": 20,
       "знаменатель": 15, "слепое": 15}


class Зона:
    """Строка паспорта: зона, её механизмы и балл защищённости."""

    def __init__(self, имя: str, механизмы: list[str]):
        self.имя = имя
        self.механизмы = механизмы
        self.балл = 0
        self.чего_нет: list[str] = []


def найти(имя: str) -> Path | None:
    """Путь к механизму по имени файла. None — объявлен, но не существует."""
    for каталог in КАТАЛОГИ:
        п = БАЗА / каталог / Path(имя).name
        if п.is_file():
            return п
    # механизмы китов лежат в `<кит>/bin/`
    for п in БАЗА.glob(f"*/bin/{Path(имя).name}"):
        if п.is_file():
            return п
    return None


def конвейер_текст() -> str:
    """Склейка файлов конвейера: в ней ищется имя механизма."""
    из = []
    for отн in КОНВЕЙЕР:
        п = БАЗА / отн
        if п.is_file():
            из.append(п.read_text(encoding="utf-8", errors="replace"))
    for п in sorted((БАЗА / ".claude" / "hooks").glob("*.sh")):
        из.append(п.read_text(encoding="utf-8", errors="replace"))
    for п in sorted((БАЗА / ".githooks").glob("*")):
        if п.is_file():
            из.append(п.read_text(encoding="utf-8", errors="replace"))
    return "\n".join(из)


РАЗДЕЛ_ОБЪЯВЛЕНИЯ = "## §4."


def только_объявление(текст: str) -> str:
    """Таблица зон из §4 — и ничего больше.

    🔴 ПЕРВАЯ РЕДАКЦИЯ РАЗБИРАЛА ВСЕ ТАБЛИЦЫ ДОКУМЕНТА и насчитала 44 зоны
    вместо 26: в счёт пошли сравнение с `104` из §1, слагаемые балла из §2
    и разбор незащищённых зон из §5. Восемнадцать выдуманных зон с нулевым
    баллом уронили общий балл и при этом выглядели как настоящая находка.

    Это тот же дефект, что `ARCH-005`, только с обратным знаком: там охват
    был УЖЕ множества и отчёт о подмножестве выглядел полным, здесь охват
    ШИРЕ множества и в отчёт попало то, чего в системе нет. Оба случая
    неотличимы изнутри отчёта — поэтому граница разбора названа явно.
    """
    начало = текст.find(РАЗДЕЛ_ОБЪЯВЛЕНИЯ)
    if начало == -1:
        return ""
    конец = текст.find("\n## ", начало + len(РАЗДЕЛ_ОБЪЯВЛЕНИЯ))
    return текст[начало:конец if конец != -1 else len(текст)]


def разобрать_паспорт(текст: str) -> list[Зона]:
    """Зоны из таблицы паспорта. Источник правды — документ, не код.

    🔴 Объявление живёт в документе НАМЕРЕННО: зона, про которую забыли
    написать, обязана быть видна человеку, читающему паспорт, а не только
    скрипту. Две копии списка (в коде и в тексте) разошлись бы молча.
    """
    зоны: list[Зона] = []
    for строка in только_объявление(текст).splitlines():
        if not строка.startswith("| "):
            continue
        клетки = [к.strip() for к in строка.strip().strip("|").split("|")]
        if len(клетки) < 3 or set(клетки[0]) <= set("-: "):
            continue
        имя = клетки[0].strip("* ")
        if not имя or имя.lower() in ("зона", "зона работы"):
            continue
        зоны.append(Зона(имя, ИМЯ_МЕХАНИЗМА.findall(клетки[2])))
    return зоны


def оценить(зона: Зона, конвейер: str) -> None:
    """Балл зоны из пяти измеримых слагаемых."""
    живые = [(имя, найти(имя)) for имя in зона.механизмы]
    существующие = [(имя, п) for имя, п in живые if п is not None]
    пропавшие = [имя for имя, п in живые if п is None]
    if пропавшие:
        зона.чего_нет.append("объявлен, но отсутствует: " + ", ".join(пропавшие))

    if not существующие:
        зона.балл = 0
        зона.чего_нет.insert(0, "исполнителя нет вовсе — держится на внимании")
        return

    балл = ВЕС["существует"]

    if any(Path(имя).name in конвейер for имя, _ in существующие):
        балл += ВЕС["конвейер"]
    else:
        зона.чего_нет.append("никто не зовёт автоматически — запускается руками")

    тексты = [п.read_text(encoding="utf-8", errors="replace") for _, п in существующие]

    def доля(признаки: tuple[str, ...]) -> float:
        попало = sum(1 for т in тексты if any(п in т for п in признаки))
        return попало / len(тексты)

    д_канарейка, д_знаменатель, д_слепое = (доля(ПРИЗНАК_КАНАРЕЙКИ),
                                            доля(ПРИЗНАК_ЗНАМЕНАТЕЛЯ),
                                            доля(ПРИЗНАК_СЛЕПОГО))
    балл += ВЕС["канарейка"] * д_канарейка
    балл += ВЕС["знаменатель"] * д_знаменатель
    балл += ВЕС["слепое"] * д_слепое

    if д_канарейка < 1:
        зона.чего_нет.append(f"канарейка у {д_канарейка:.0%} механизмов")
    if д_знаменатель < 1:
        зона.чего_нет.append(f"знаменатель охвата печатает {д_знаменатель:.0%}")
    if д_слепое < 1:
        зона.чего_нет.append(f"слепое пятно объявляет {д_слепое:.0%}")
    зона.балл = round(балл)


def значок(балл: int) -> str:
    return "🟢" if балл >= 90 else "🟡" if балл >= 70 else "🔴"


def selftest() -> int:
    """Паспорт обязан ставить ноль зоне без исполнителя и 100 — полной.

    🔴 Канарейка здесь не формальность: инструмент, который меряет защиту,
    при поломке даёт самый опасный отказ — уверенное «всё защищено».
    """
    документ = (
        "# заголовок\n\n## §1. Постороннее\n\n"
        "| Строка | Которую |\n|---|---|\n| не считать | нельзя | `publish.py` |\n\n"
        f"{РАЗДЕЛ_ОБЪЯВЛЕНИЯ} Зоны\n\n"
        "| Зона | Что |\n|---|---|\n"
        "| пустая | нет | — |\n"
        "| живая | есть | `revision_check.py` |\n\n"
        "## §5. Тоже постороннее\n\n"
        "| Ещё | Одна |\n|---|---|\n| не зона | нет | |\n")
    зоны = разобрать_паспорт(документ)
    assert [з.имя for з in зоны] == ["пустая", "живая"], (
        f"разобрано лишнее или потеряно нужное: {[з.имя for з in зоны]}")
    конвейер = конвейер_текст()
    for з in зоны:
        оценить(з, конвейер)
    пустая, живая = зоны
    assert пустая.балл == 0, f"зона без механизма обязана давать 0, дала {пустая.балл}"
    assert живая.балл > 0, "зона с живым механизмом обязана давать больше нуля"
    выдуманная = Зона("выдуманная", ["ne_sushchestvuet_vovse.py"])
    оценить(выдуманная, конвейер)
    assert выдуманная.балл == 0, "несуществующий механизм не даёт баллов"
    assert найти("ne_sushchestvuet_vovse.py") is None, "поиск обязан вернуть None"
    assert найти("revision_check.py") is not None, "живой механизм обязан находиться"
    print("🟢 канарейка паспорта: разбирается только таблица §4, зона без "
          "исполнителя даёт 0, выдуманный механизм баллов не даёт")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--verbose", action="store_true", help="чего не хватает по зонам")
    ap.add_argument("--gate", type=int, metavar="NN",
                    help="код возврата 1, если общий балл ниже порога")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()

    if not ПАСПОРТ.is_file():
        print(f"🔴 нет паспорта зон: {ПАСПОРТ.relative_to(БАЗА)}")
        return 1

    зоны = разобрать_паспорт(ПАСПОРТ.read_text(encoding="utf-8"))
    if not зоны:
        print("🔴 в паспорте не разобрана ни одна зона — таблица сломана")
        return 1

    конвейер = конвейер_текст()
    for з in зоны:
        оценить(з, конвейер)

    ширина = max(len(з.имя) for з in зоны)
    for з in sorted(зоны, key=lambda з: з.балл):
        print(f"{значок(з.балл)} {з.имя.ljust(ширина)}  {з.балл:3d}/100  "
              f"механизмов: {len(з.механизмы)}")
        if a.verbose and з.чего_нет:
            for строка in з.чего_нет:
                print(f"      · {строка}")

    общий = round(sum(з.балл for з in зоны) / len(зоны))
    без_исполнителя = sum(1 for з in зоны if з.балл == 0)
    print(f"\nзон в паспорте: {len(зоны)} · без исполнителя: {без_исполнителя} · "
          f"механизмов объявлено: {sum(len(з.механизмы) for з in зоны)}")
    print(f"ОБЩИЙ БАЛЛ ЗАЩИЩЁННОСТИ: {значок(общий)} {общий}/100")
    print("🔴 Балл говорит, что механизм ЕСТЬ и ЗОВЁТСЯ. Что он проверяет "
          "ВЕРНУЮ вещь, паспорт не знает (verification, не validation).")

    if a.gate is not None and общий < a.gate:
        print(f"🔴 порог {a.gate} не взят")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
