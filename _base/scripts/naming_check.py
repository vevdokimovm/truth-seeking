#!/usr/bin/env python3
"""naming_check.py — единый нейминг по всей репе: перечислить нарушения.

🔴 ЗАКАЗ ВЛАДЕЛЬЦА 29.09.2026, дословно: «поправить по всей базе нейминг чтобы
был одинаковый единый. у нас есть стандарт и нужно чтобы ВЕЗДЕ были одни
в папках подпапках файлах и тд. потому что где то есть например числа где то
нет».

Правило и его основание — `00-infrastructure/01-repo-standard.md` §1.
Коротко: **номер — это адрес и порядок**. Он ставится там, где есть порядок
чтения или ссылки по номеру, и не ставится больше нигде.

    каталог верхнего уровня, читаемый человеком  → NN-kebab-case
    каталог служебный, адресуемый машиной        → lowercase без номера
    файл-константа репы                          → UPPER-CASE.md без номера
    документ внутри нумерованного каталога       → NN-kebab-case.md
    документ внутри ненумерованного каталога     → kebab-case.md

🔴 ПЕРЕИМЕНОВЫВАТЬ САМ НЕ УМЕЕТ, И ЭТО НАМЕРЕННО. Имя документа — адрес:
на `98-readme-standard.md` ссылаются по номеру, на `pitfalls.md` — по имени.
Смена имени обязана идти вместе с правкой всех ссылок, а решение, какое имя
верное, — суждение (`71` §7г-бис). Инструмент перечисляет и считает; решает
вахта. Ровно то правило, которым `ROADMAP` §P1.6 ограничивает агентов.

ЗАПУСК
    naming_check.py                  нарушения по текущей репе
    naming_check.py --репа <путь>    по другой репе
    naming_check.py --selftest
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

КАТАЛОГ_С_НОМЕРОМ = re.compile(r"^\d{2}-[a-z0-9]+(-[a-z0-9]+)*$")
КАТАЛОГ_СЛУЖЕБНЫЙ = {"scripts", "tests", "templates", "reports"}
ДОК_С_НОМЕРОМ = re.compile(r"^\d+[a-z]?-[a-z0-9]+(-[a-z0-9]+)*\.md$")
# 🔴 Дата — законный порядок, а не «номер без порядка». Первая редакция этого
# файла запрета не различала и пометила 22 отчёта и прогона нарушением. Ошибка
# была в правиле, не в файлах: дату не надо назначать и поддерживать, она
# упорядочивает сама. Поймано первым же прогоном по диску (§1б, класс
# «документ-событие»).
ДОК_СОБЫТИЕ = re.compile(r"^\d{4}-\d{2}-\d{2}-[a-z0-9]+(-[a-z0-9]+)*\.md$")
ДОК_БЕЗ_НОМЕРА = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*\.md$")
КОНСТАНТА = re.compile(r"^[A-Z][A-Z0-9]*(-[A-Z0-9]+)*\.md$")
# 🔴 Ещё три законных класса, найденных ПРОГОНОМ, а не придуманных заранее.
# Первая редакция знала только четыре класса и пометила нарушением
# `00-CLAUDE-STOP.md`, `ST-001-raw-exports.md`, `deploy-SPEC.md` и `Memory.md`.
# Ни один из них не дефект: у каждого имя работает адресом — числовой префикс
# прибивает файл к началу листинга, код карточки реестра и есть ссылка
# (`СТ-001.4`), составное «предмет-КОНСТАНТА» держит группу документов одного
# артефакта рядом. Урок тот же, что с датой: правило, написанное до прогона,
# ошибается в сторону «слишком узко».
КОНСТАНТА_С_ПРЕФИКСОМ = re.compile(r"^\d{2}-[A-Z][A-Z0-9]*(-[A-Za-z0-9]+)*\.md$")
КАРТОЧКА_РЕЕСТРА = re.compile(r"^[A-Z]{2,4}-\d{3}(-[a-z0-9]+)*\.md$")
СОСТАВНАЯ = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*-[A-Z][A-Z0-9]*\.md$")
# Та же форма наоборот: `EXAMPLE-lawyer.md`, `TEMPLATE-role.md`. Константа
# впереди группирует однотипные файлы в листинге — это её работа, и она
# такая же законная, как `deploy-SPEC.md`.
СОСТАВНАЯ_ОБРАТНАЯ = re.compile(r"^[A-Z][A-Z0-9]*-[a-z0-9]+(-[a-z0-9]+)*\.md$")
# Имена, продиктованные ВНЕШНИМ инструментом: Claude Code читает их буквально
# через `@Memory.md` в `CLAUDE.md`. Переименование сломало бы загрузку контекста,
# поэтому это не нарушение, а внешнее ограничение — и названо им явно.
ЗАДАНЫ_ИЗВНЕ = {"Memory.md", "Context.md", "Skills.md", "Agents.md", "CLAUDE.md"}

# Имена, которые обязаны быть константами: по ним грепают гейты и хуки.
КОНСТАНТЫ = {"README.md", "CHANGELOG.md", "ROADMAP.md", "TASKS.md",
             "WATCHLOG.md", "START-HERE.md", "MANIFEST.md", "ONBOARDING.md",
             "INFRA-UPDATES.md", "STATE-NOW.md", "PITFALLS.md", "PLAN.md",
             "STANDARD.md", "CHECKLIST.md", "PROCEDURE.md", "QUEUE.md",
             "RUNS.md", "SWITCHES.md", "LAUNCH-BRIEF.md", "BOARD.md",
             "BACKLOG.md", "RESEARCH.md", "METHOD.md", "LEDGER.md"}

# Латиница, которой записано русское слово. Признак — сочетания, невозможные
# в английском корне. Список намеренно узкий: ловим уверенно, а не широко.
ТРАНСЛИТ = re.compile(
    r"(kh|zh|shch|yy|iy|tsiy|nie-|nyy|ova|stvo|skiy|vaniya|yah|yu[a-z])",
    re.I)

НЕ_СМОТРИМ = {".git", "_base", "__pycache__", ".venv", "node_modules",
              ".pytest_cache", ".ipynb_checkpoints", "__MACOSX"}


class Нарушение:
    def __init__(self, путь: str, класс: str, что: str):
        self.путь, self.класс, self.что = путь, класс, что

    def __str__(self) -> str:
        return f"[{self.класс}] {self.путь} — {self.что}"


def каталоги_верхнего(корень: Path) -> list[Нарушение]:
    """N1 — форма имени · N6 — уникальность номера.

    🔴 N6 добавлен 29.09.2026 по находке ВЛАДЕЛЬЦА: «почему там две папки
    с номером 00». Проверка смотрела на шаблон имени и была слепа к тому,
    что два каталога делят один номер. А номер — это позиция (§1а): два
    каталога на одной позиции означают, что порядка нет вовсе, и обещание
    номера ложно. Форма при этом у обоих безупречна, поэтому проверка формы
    такой дефект не видит по построению.
    """
    беды = []
    номера: dict[str, list[str]] = {}
    for п in sorted(корень.iterdir()):
        if not п.is_dir() or п.name.startswith(".") or п.name in НЕ_СМОТРИМ:
            continue
        if п.name in КАТАЛОГ_СЛУЖЕБНЫЙ:
            continue
        if not КАТАЛОГ_С_НОМЕРОМ.match(п.name):
            беды.append(Нарушение(f"{п.name}/", "N1",
                                  "каталог верхнего уровня без префикса `NN-` "
                                  "или не kebab-case (§1б)"))
            continue
        номера.setdefault(п.name[:2], []).append(п.name)
    for номер, кто in sorted(номера.items()):
        if len(кто) > 1:
            беды.append(Нарушение(", ".join(f"{к}/" for к in кто), "N6",
                                  f"номер {номер} занят {len(кто)} каталогами — "
                                  f"позиция не определена (§1а)"))
    return беды


def документы(корень: Path) -> list[Нарушение]:
    беды = []
    for файл in sorted(корень.rglob("*.md")):
        if any(ч in НЕ_СМОТРИМ or ч.startswith(".") for ч in файл.parts):
            continue
        имя, род = файл.name, файл.parent
        отн = str(файл.relative_to(корень))

        if ТРАНСЛИТ.search(файл.stem) and not КОНСТАНТА.match(имя):
            беды.append(Нарушение(отн, "N4", "транслитерация в имени — "
                                             "ни английский, ни русский (§1в.1)"))
            continue
        if "_" in файл.stem:
            беды.append(Нарушение(отн, "N5", "подчёркивание вместо дефиса (§1в.2)"))
            continue
        if имя in КОНСТАНТЫ or КОНСТАНТА.match(имя) or имя in ЗАДАНЫ_ИЗВНЕ:
            continue
        if (ДОК_СОБЫТИЕ.match(имя) or КОНСТАНТА_С_ПРЕФИКСОМ.match(имя)
                or КАРТОЧКА_РЕЕСТРА.match(имя) or СОСТАВНАЯ.match(имя)
                or СОСТАВНАЯ_ОБРАТНАЯ.match(имя)):
            continue
        # 🔴 Номер у документа законен ровно тогда, когда нумерован его каталог:
        # номер — позиция в читаемой последовательности, а последовательность
        # задаёт каталог, а не файл сам по себе.
        родитель_нумерован = bool(КАТАЛОГ_С_НОМЕРОМ.match(род.name)) or род == корень
        if ДОК_С_НОМЕРОМ.match(имя):
            if not родитель_нумерован:
                беды.append(Нарушение(отн, "N3", "номер у документа в ненумерованном "
                                                 "каталоге — порядка нет, номер врёт (§1в.3)"))
        elif not ДОК_БЕЗ_НОМЕРА.match(имя):
            беды.append(Нарушение(отн, "N2", "не kebab-case и не константа (§1б)"))
    return беды


def selftest() -> int:
    assert КАТАЛОГ_С_НОМЕРОМ.match("05-infra-synthesis-lab")
    assert not КАТАЛОГ_С_НОМЕРОМ.match("scripts")
    assert ДОК_С_НОМЕРОМ.match("98-readme-standard.md")
    assert ДОК_БЕЗ_НОМЕРА.match("adr-template.md")
    assert ДОК_СОБЫТИЕ.match("2026-08-22-telegram-export.md"), "дата — законный порядок"
    assert not ДОК_СОБЫТИЕ.match("98-readme-standard.md")
    assert КОНСТАНТА_С_ПРЕФИКСОМ.match("00-CLAUDE-STOP.md")
    assert КОНСТАНТА_С_ПРЕФИКСОМ.match("00-MANIFEST-attack-on-titan.md")
    assert КАРТОЧКА_РЕЕСТРА.match("ST-001-raw-exports.md")
    assert СОСТАВНАЯ.match("deploy-SPEC.md") and СОСТАВНАЯ.match("repos-map-CHANGELOG.md")
    assert not СОСТАВНАЯ.match("report-types.md"), "подчёркивание не составное имя"
    assert КОНСТАНТА.match("START-HERE.md") and КОНСТАНТА.match("README.md")
    # 🔴 Имя собирается из кусков, а не пишется литералом. 29.09.2026 здесь
    # стоял `ROADMAP_HISTORY.md`, и проход правки ссылок (`naming_fix.py`)
    # честно заменил его на дефисную форму — вместе со всеми настоящими
    # ссылками. Тест стал проверять обратное тому, ради чего написан, и упал.
    # Фикстура теста не должна совпадать с живым именем в репе.
    assert not КОНСТАНТА.match("SOME" + "_" + "NAME.md"), "подчёркивание не константа"
    assert ТРАНСЛИТ.search("put-s-iisusom-khristom")
    assert ТРАНСЛИТ.search("kontekst-vasiliy-edinyy")
    assert not ТРАНСЛИТ.search("readme-standard"), "английское имя не ловится"
    assert not ТРАНСЛИТ.search("architecture-defects")
    print("🟢 selftest: классы имён различаются, транслитерация ловится, "
          "английские имена ложно не срабатывают")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--репа", type=Path,
                    default=Path(__file__).resolve().parent.parent)
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()

    корень = a.репа.expanduser().resolve()
    беды = каталоги_верхнего(корень) + документы(корень)
    if not беды:
        print(f"🟢 нейминг единый: нарушений нет ({корень.name})")
        return 0

    по_классам: dict[str, list[Нарушение]] = {}
    for б in беды:
        по_классам.setdefault(б.класс, []).append(б)
    for класс in sorted(по_классам):
        print(f"\n🔴 {класс} — {len(по_классам[класс])}")
        for б in по_классам[класс]:
            print(f"   · {б.путь} — {б.что}")
    print(f"\nнарушений: {len(беды)} · репа: {корень.name}")
    print("🔴 Переименование — вручную: имя документа есть адрес, "
          "смена требует правки всех ссылок на него.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
