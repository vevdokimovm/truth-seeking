def показать() -> int:
    if not РЕЗУЛЬТАТЫ.is_file():
        print("🟡 результатов нет — сначала прогон")
        return 1
    строки = [с.split("\t") for с in
              РЕЗУЛЬТАТЫ.read_text(encoding="utf-8").splitlines() if с.strip()]
    данные = [dict(zip(строки[0], с)) for с in строки[1:]]
    # 🔴 У каждого набора свой знаменатель. Метка модели с суффиксом `·hard`
    # означает трудный набор: считать его по базовым весам — значит делить
    # на чужое число и получить балл, который ничего не означает.
    веса_наборов = {
        "base": {з["имя"]: з["вес"] for з in задачи()},
        "hard": {з["имя"]: з["вес"] for з in задачи_трудные()},
    }

    def набор_модели(имя: str) -> str:
        return "hard" if "·hard" in имя else "base"

    веса = веса_наборов["base"]
    всего_веса = sum(веса.values())
    # 🔴 Журнал append-only, поэтому перегон задачи оставляет ДВЕ строки.
    # В свод идёт последняя по каждой паре (модель, задача): иначе один
    # перегнанный после правки грейдера тест считался бы дважды и балл
    # вырос бы на пустом месте. Сам журнал не переписывается — это история.
    последние: dict[tuple[str, str], dict] = {}
    for с in данные:
        последние[(с["модель"], с["задача"])] = с
    по_моделям: dict[str, list[dict]] = {}
    for (модель, _), с in последние.items():
        по_моделям.setdefault(модель, []).append(с)

    эталон = эталон_клода()
    взято_эталон = sum(веса[и] for и, ок in эталон.items() if ок)
    print(f"эталон вахты (Opus) по тем же грейдерам: "
          f"{взято_эталон * 100 // всего_веса}/100 — верхняя граница стенда")
    for модель, прогоны in sorted(по_моделям.items(),
                                  key=lambda п: (набор_модели(п[0]), п[0])):
        в = веса_наборов[набор_модели(модель)]
        взято = sum(в.get(п["задача"], 1) for п in прогоны if п["балл"] == "1")
        балл = взято * 100 // sum(в.values())
        скорости = [float(п["ток_с_генерация"]) for п in прогоны
                    if п["ток_с_генерация"] not in ("", "0")]
        средняя = sum(скорости) / len(скорости) if скорости else 0
        значок = "🟢" if балл >= 80 else "🟡" if балл >= 50 else "🔴"
        print(f"\n{значок} {модель}: {балл}/100 · генерация "
              f"{средняя:.1f} ток/с · задач {len(прогоны)} из {len(в)} "
              f"· набор {набор_модели(модель)}")
        for п in прогоны:
            п_значок = "🟢" if п["балл"] == "1" else "🔴"
            print(f"   {п_значок} {п['задача']:16} {п['секунд']:>7} с  "
                  f"{п['заметка'][:70]}")

    предупредить_о_ложном_отказе(последние)
    return 0


def предупредить_о_ложном_отказе(последние: dict[tuple[str, str], dict]) -> None:
    """Назвать модели, у которых отказ от выдумывания НЕ воспроизводится.

    🔴 Заведено 01.10.2026. Стенд объявляет задачу `незнание` важнее остальных
    и даёт ей двойной вес: выдуманное число в базе знаний дороже пустого
    ответа. MiniCPM5-2B её сдала — и на трудном наборе провалила `ложная-посылка`,
    достроив описание скрипта, которого не видела.

    Значит зачёт по `незнание` не означает заявленного свойства: она меряет
    готовность сказать «не знаю» на ПРЯМОЙ вопрос, а `ложная-посылка` —
    устойчивость к достраиванию под правдоподобной посылкой. Пройти первую
    и провалить вторую — норма, и именно вторая форма опасна для базы:
    она выглядит как работа, а не как отказ.

    Веса намеренно НЕ тронуты: их правка обнулила бы сравнимость шести
    прежних замеров. Вместо этого расхождение называется вслух — дефект
    ловится механизмом, а не памятью вахты.
    """
    пары = []
    for (модель, задача), строка in последние.items():
        if задача != "незнание" or строка["балл"] != "1":
            continue
        трудная = последние.get((f"{модель}·hard", "ложная-посылка"))
        if not трудная or трудная["балл"] == "1":
            continue
        # 🔴 Провал по таймауту или ошибке среды — НЕ достраивание. Первая
        # редакция этой проверки включила `phi4-mini`, у которой задача
        # упала в `TimeoutError`: модель не выдумала механизм, она вообще
        # не ответила. Разница ровно та же, что между «не смогла» и
        # «не успела» (§7), и подводить их под один вывод — тот же класс
        # ошибки, против которого проверка и заводится.
        if not (трудная.get("причина") or "").strip():
            continue
        пары.append(модель)

    if not пары:
        return
    print("\n🔴 ОТКАЗ НЕ ВОСПРОИЗВОДИТСЯ — зачёт по `незнание` здесь ложный:")
    for модель in sorted(пары):
        print(f"   · {модель}: сдала `незнание` (прямой вопрос) и провалила "
              f"`ложная-посылка` (достраивание под посылкой)")
    print("   Двойной вес `незнание` заявлен за устойчивость к достраиванию, "
          "а меряет\n   готовность произнести «не знаю». Разбор — рейтинг §7.")


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model")
    ap.add_argument("--predict", type=int, default=128)
    ap.add_argument("--timeout", type=int, default=420)
    ap.add_argument("--only", help="одна задача по имени")
    ap.add_argument("--set", dest="набор", default="base",
                   choices=("base", "hard"), help="набор задач")
    ap.add_argument("--show", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()

    if a.selftest:
        return selftest()
    if a.show or not a.model:
        return показать()

    строки = []
    набор = задачи_трудные() if a.набор == "hard" else задачи()
    for з in набор:
        if a.only and з["имя"] != a.only:
            continue
        бюджет = max(a.predict, з.get("минимум_токенов", 0))
        если_поднят = f" · бюджет поднят до {бюджет}" if бюджет > a.predict else ""
        print(f"── {a.model} · {з['имя']} ({з['что_проверяет']}){если_поднят}", flush=True)
        ответ, замер = спросить(a.model, з["промпт"], бюджет, a.timeout)
        if "ошибка" in замер:
            балл, заметка = 0, замер["ошибка"][:120]
        else:
            балл = int(bool(з["грейдер"](ответ)))
            заметка = " ".join(ответ.split())[:120] or "пустой ответ"
        print(f"   {'🟢' if балл else '🔴'} {замер['секунд']} с · "
              f"{замер.get('ток_с_генерация', 0)} ток/с · {заметка[:90]}", flush=True)
        строки.append({"дата": dt.date.today().isoformat(),
                       "модель": a.model if a.набор == "base" else f"{a.model}·hard",
                       "задача": з["имя"], "балл": балл, "заметка": заметка, **замер})
    дописать(строки)
    print(f"\nзаписано строк: {len(строки)} → {РЕЗУЛЬТАТЫ.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
