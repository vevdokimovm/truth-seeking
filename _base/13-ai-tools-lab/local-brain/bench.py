def лямбда_схема(ответ: str) -> bool:
    м = re.search(r"\{.*?\}", ответ, re.S)
    if not м:
        return False
    try:
        д = json.loads(м.group(0))
    except ValueError:
        return False
    # 🔴 ПРЕФИКС `v` ПРИНИМАЕТСЯ, И ЭТО ИСПРАВЛЕНИЕ ГРЕЙДЕРА, А НЕ ПОСЛАБЛЕНИЕ.
    # Первая редакция требовала ровно «4.216.0» и поставила ноль за ответ
    # `"версия": "v4.216.0"` — при том что в исходной строке стоит именно
    # `v4.216.0`. То есть проверка мерила ОФОРМЛЕНИЕ вместо смысла и объявила
    # верное извлечение ошибкой. Ровно тот класс дефекта, который в реестре
    # системы уже записан: регулярка, зависящая от разметки, молчит при
    # настоящем дефекте и кричит при его отсутствии. Задача просила извлечь
    # версию, а не нормализовать её — нормализация не была задана.
    версия = str(д.get("версия", "")).strip().lstrip("vV")
    return (версия == "4.216.0"
            and str(д.get("дата", "")).strip() == "2026-09-30"
            and str(д.get("файлов", "")).strip() in ("784", "784.0"))


def лямбда_числа(ответ: str) -> bool:
    нужные = ("112", "989", "100", "389", "29")
    найдены = all(n in ответ for n in нужные)
    # 🔴 «Одно предложение» проверяется тоже: модель, вывалившая абзац,
    # задачу не выполнила — в базу пойдёт не тезис, а пересказ.
    предложений = len([ч for ч in re.split(r"[.!?]\s", ответ.strip()) if ч.strip()])
    return найдены and предложений <= 3


