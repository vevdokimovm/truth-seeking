def лямбда_коммит(ответ: str) -> bool:
    строки = [с.strip().strip("`") for с in ответ.strip().splitlines() if с.strip()]
    if not строки:
        return False
    строка = next((с for с in строки if re.match(
        r"^(feat|fix|docs|chore|refactor|test|perf|style|build|ci)(\(.+?\))?: .{6,}",
        с)), "")
    if not строка or len(строка) > 90:
        return False
    return not re.search(r"claude|anthropic|co-authored", ответ, re.I)


