def спросить(модель: str, промпт: str, предсказать: int,
             таймаут: int) -> tuple[str, dict]:
    # 🔴 `think: false` ОБЯЗАТЕЛЕН, И ЭТО НЕ НАСТРОЙКА ВКУСА. Gemma 4 E2B —
    # «думающая» модель: при включённом размышлении весь бюджет токенов уходит
    # в поле `thinking`, `response` приходит ПУСТЫМ, а причина остановки —
    # `length`. Замер 30.09.2026: 64 токена, 80 секунд, ноль полезного вывода.
    # На машине, выдающей 6 ток/с, преамбула размышления стоит десятки секунд
    # до первого нужного слова. Заодно поле `thinking` замеряется отдельно:
    # видно, сколько модель тратит на себя.
    тело = json.dumps({
        "model": модель, "prompt": промпт, "stream": False, "think": False,
        "options": {"temperature": 0, "num_predict": предсказать},
    }).encode("utf-8")
    запрос = urllib.request.Request(API, data=тело,
                                    headers={"Content-Type": "application/json"})
    начало = time.time()
    try:
        with urllib.request.urlopen(запрос, timeout=таймаут) as о:
            д = json.loads(о.read().decode("utf-8"))
    except (urllib.error.URLError, TimeoutError, OSError, ValueError) as e:
        return "", {"ошибка": f"{type(e).__name__}: {e}",
                    "секунд": round(time.time() - начало, 1)}
    отдача = д.get("eval_count", 0)
    длительность = д.get("eval_duration", 0) / 1e9
    чтение = д.get("prompt_eval_count", 0)
    чтение_с = д.get("prompt_eval_duration", 0) / 1e9
    размышление = len((д.get("thinking") or "").split())
    return д.get("response", ""), {
        "секунд": round(time.time() - начало, 1),
        "слов_размышления": размышление,
        "причина": д.get("done_reason", ""),
        "токенов_выдано": отдача,
        "ток_с_генерация": round(отдача / длительность, 2) if длительность else 0,
        "токенов_промпта": чтение,
        "ток_с_чтение": round(чтение / чтение_с, 2) if чтение_с else 0,
    }


