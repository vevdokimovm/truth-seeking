# 🔴 ДВЕ СХЕМЫ, И ЭТО НЕ УКРАШЕНИЕ. Замер 01.10.2026: при кириллических именах
# аргументов Granite 4.0-3B прислала ключ `пун` вместо `путь` — инструмент
# и файл выбраны верно, ключ искажён, — а MiniCPM5-2B выбирала вообще не тот
# инструмент. С латинскими именами обе дали идеальный вызов и поднялись
# с 33 до 50 из 100; `base-local` на Qwen не изменилась.
#
# Значит прежний единственный вариант схемы мерил не способность вызывать
# инструмент, а качество кириллического токенизатора модели. Обе схемы
# оставлены: латинская — рабочая, кириллическая — воспроизводит дефект,
# потому что утверждение «кириллица стоит ступени» должно проверяться
# запуском, а не ссылкой на этот комментарий.
#
# Тексты задач остаются русскими в обеих схемах: меняется ОДНА переменная.
def _схема(чтение: str, ключ_путь: str, запуск: str, ключ_скрипт: str) -> dict:
    """Собрать описание пары инструментов под заданные имена.

    Args:
        чтение: имя инструмента чтения файла.
        ключ_путь: имя аргумента с путём.
        запуск: имя инструмента запуска проверки.
        ключ_скрипт: имя аргумента с именем скрипта.

    Returns:
        Словарь с именами и готовым списком `tools` для Ollama.
    """
    return {
        "чтение": чтение,
        "ключ_путь": ключ_путь,
        "запуск": запуск,
        "ключ_скрипт": ключ_скрипт,
        "инструменты": [
            {
                "type": "function",
                "function": {
                    "name": чтение,
                    "description": ("Прочитать текстовый файл репозитория "
                                    "и вернуть его содержимое"),
                    "parameters": {
                        "type": "object",
                        "properties": {
                            ключ_путь: {"type": "string",
                                        "description": "путь от корня репозитория"},
                        },
                        "required": [ключ_путь],
                    },
                },
            },
            {
                "type": "function",
                "function": {
                    "name": запуск,
                    "description": ("Запустить скрипт-проверку репозитория "
                                    "и вернуть её вывод"),
                    "parameters": {
                        "type": "object",
                        "properties": {
                            ключ_скрипт: {"type": "string",
                                          "description": "имя скрипта из scripts/"},
                        },
                        "required": [ключ_скрипт],
                    },
                },
            },
        ],
    }


СХЕМЫ = {
    "en": _схема("read_file", "path", "run_check", "script"),
    "ru": _схема("прочитать_файл", "путь", "запустить_проверку", "скрипт"),
}


def вызовы(ответ: dict) -> list[tuple[str, dict]]:
    """[(имя инструмента, аргументы)] из ответа Ollama. Пусто — вызова не было."""
    из = []
    for в in (ответ.get("message", {}) or {}).get("tool_calls", []) or []:
        ф = в.get("function", {})
        арг = ф.get("arguments", {})
        if isinstance(арг, str):
            try:
                арг = json.loads(арг)
            except ValueError:
                арг = {}
        # 🔴 Гарантировать СЛОВАРЬ, а не надеяться на него. Ревью 01.10.2026:
        # модель может прислать `arguments` списком — либо строкой
        # `'["reports/pitfalls.md"]'`, которая разбирается в список. Тогда
        # `арг.get(...)` в грейдере даёт AttributeError, прогон падает
        # и уносит все уже собранные ступени. Не-словарь — это отсутствие
        # именованных аргументов, то есть провал ступени, а не сбой стенда.
        if not isinstance(арг, dict):
            арг = {}
        из.append((ф.get("name", ""), арг))
    return из


def ступень_1(ответ: dict, схема: dict) -> bool:
    """Один вызов: прочитать именно тот файл, о котором спросили."""
    в = вызовы(ответ)
    if len(в) != 1:
        return False
    имя, арг = в[0]
    путь = str(арг.get(схема["ключ_путь"], "")).strip().removeprefix("./")
    return имя == схема["чтение"] and путь == "reports/pitfalls.md"


def ступень_2(ответ: dict, схема: dict) -> bool:
    """Выбор из двух: тут нужен запуск проверки, а не чтение файла."""
    в = вызовы(ответ)
    if len(в) != 1:
        return False
    имя, арг = в[0]
    скрипт = str(арг.get(схема["ключ_скрипт"], "")).strip()
    return имя == схема["запуск"] and "revision_check" in скрипт


def ступень_3(ответ: dict, схема: dict) -> bool:
    """Второй ход: получив вывод проверки с одним падением, прочитать ИМЕННО
    тот файл, который в падении назван, — а не начать сначала."""
    в = вызовы(ответ)
    if len(в) != 1:
        return False
    имя, арг = в[0]
    путь = str(арг.get(схема["ключ_путь"], "")).strip().removeprefix("./")
    return имя == схема["чтение"] and путь == "00-infrastructure/45-roadmap-and-tasks.md"


