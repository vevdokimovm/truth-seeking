def спросить(модель: str, сообщения: list[dict], таймаут: int,
             схема: dict) -> tuple[dict, dict]:
    тело = json.dumps({
        "model": модель, "messages": сообщения, "tools": схема["инструменты"],
        "stream": False, "think": False,
        "options": {"temperature": 0, "num_predict": 200},
    }).encode("utf-8")
    запрос = urllib.request.Request(API, data=тело,
                                    headers={"Content-Type": "application/json"})
    начало = time.time()
    try:
        with urllib.request.urlopen(запрос, timeout=таймаут) as о:
            д = json.loads(о.read().decode("utf-8"))
    except (urllib.error.URLError, TimeoutError, OSError, ValueError) as e:
        # 🔴 Тело ответа обязательно. Ollama пишет причину отказа именно в нём
        # («model does not support tools» и подобное), а `HTTPError` в строке
        # даёт только «HTTP Error 400: Bad Request» — и в журнале
        # инфраструктурный отказ становится неотличим от честного провала
        # ступени. Числа этого стенда идут в рейтинг, поэтому различать
        # обязательно (ревью 01.10.2026).
        подробно = ""
        if isinstance(e, urllib.error.HTTPError):
            try:
                подробно = " · " + e.read().decode("utf-8", "replace")[:160]
            except OSError:
                подробно = " · тело ответа не прочиталось"
        return {}, {"ошибка": f"{type(e).__name__}: {e}{подробно}"[:280],
                    "секунд": round(time.time() - начало, 1)}
    return д, {"секунд": round(time.time() - начало, 1),
               "токенов": д.get("eval_count", 0)}


def selftest() -> int:
    """Грейдеры обязаны отличать вызов от РАССКАЗА о вызове — на обеих схемах.

    🔴 Добавлено 01.10.2026: проверка на искажённый КЛЮЧ аргумента. Granite
    прислала `пун` вместо `путь` при верном имени инструмента и верном
    значении — старая канарейка такой случай не покрывала, и разницу между
    «выбрала не тот инструмент» и «не смогла назвать ключ» стенд не видел.
    """
    for имя_схемы, с in СХЕМЫ.items():
        чт, зп = с["чтение"], с["запуск"]
        кп, кс = с["ключ_путь"], с["ключ_скрипт"]

        верный = {"message": {"tool_calls": [{"function": {
            "name": чт, "arguments": {кп: "reports/pitfalls.md"}}}]}}
        assert ступень_1(верный, с), имя_схемы

        # 🔴 Самый частый отказ малой модели: она ОПИСЫВАЕТ вызов текстом.
        словами = {"message": {"content": f"Я вызову {чт}('reports/pitfalls.md')",
                               "tool_calls": []}}
        assert not ступень_1(словами, с), "рассказ о вызове не является вызовом"

        чужой = {"message": {"tool_calls": [{"function": {
            "name": чт, "arguments": {кп: "README.md"}}}]}}
        assert not ступень_1(чужой, с), "не тот файл — не зачёт"

        # 🔴 Ключ искажён, имя инструмента и значение верны — ровно случай
        # Granite. Зачёта быть не должно: на реальном вызове такой аргумент
        # тоже не прочитается.
        ключ_битый = {"message": {"tool_calls": [{"function": {
            "name": чт, "arguments": {"пун": "reports/pitfalls.md"}}}]}}
        assert not ступень_1(ключ_битый, с), "искажённый ключ аргумента — не зачёт"

        # 🔴 Обрезка пути: снимается только префикс `./`, и ничего больше
        # (ревью 01.10.2026). Прежний `lstrip("./")` снимал ЛЮБЫЕ ведущие
        # точки и слэши, поэтому `../reports/...` и `/reports/...` шли
        # в зачёт — а по ним настоящая оболочка файл не прочитает: один
        # выходит из корня репы, другой абсолютный.
        for кривой in ("../reports/pitfalls.md", "/reports/pitfalls.md",
                       ".//reports/pitfalls.md"):
            мимо = {"message": {"tool_calls": [{"function": {
                "name": чт, "arguments": {кп: кривой}}}]}}
            assert not ступень_1(мимо, с), f"путь {кривой} не должен проходить"

        два = {"message": {"tool_calls": [
            {"function": {"name": чт, "arguments": {кп: "reports/pitfalls.md"}}},
            {"function": {"name": зп, "arguments": {кс: "x.py"}}}]}}
        assert not ступень_1(два, с), "лишний вызов — не зачёт"

        строкой = {"message": {"tool_calls": [{"function": {
            "name": зп,
            "arguments": '{"' + кс + '": "revision_check.py"}'}}]}}
        assert ступень_2(строкой, с), "аргументы строкой JSON обязаны разбираться"
        assert not ступень_2(верный, с), "чтение файла вместо запуска — не зачёт"

        цепочка = {"message": {"tool_calls": [{"function": {
            "name": чт,
            "arguments": {кп: "00-infrastructure/45-roadmap-and-tasks.md"}}}]}}
        assert ступень_3(цепочка, с), имя_схемы
        assert not ступень_3(строкой, с), "повтор проверки вместо шага — не зачёт"

        # Схема обязана давать ровно три задачи с весами 1+2+3.
        з = задачи(с)
        assert [т["имя"] for т in з] == ["один-вызов", "выбор-из-двух", "второй-ход"]
        assert sum(т["вес"] for т in з) == 6, имя_схемы

        # 🔴 Подделанный предыдущий ход в цепочке обязан называть инструмент
        # ТОЙ ЖЕ схемы, иначе модель получит чужую историю.
        цеп = з[2]["сообщения"][2]["tool_calls"][0]["function"]
        assert цеп["name"] == зп, f"{имя_схемы}: история цепочки зовёт чужой инструмент"
        assert кс in цеп["arguments"], f"{имя_схемы}: в истории чужой ключ аргумента"
        # Результат инструмента обязан ссылаться на тот же вызов той же схемы.
        assert з[2]["сообщения"][3].get("tool_name") == зп, (
            f"{имя_схемы}: результат инструмента не привязан к вызову")

    print("🟢 канарейка стенда инструментов: рассказ о вызове не считается "
          "вызовом, чужой аргумент, искажённый КЛЮЧ, лишний вызов и путь "
          "с выходом из корня (`../`, `/`) не проходят, аргументы строкой "
          "разбираются, история цепочки согласована со схемой — проверено "
          f"на схемах: {', '.join(СХЕМЫ)}")
    return 0


ПОЛЯ = ("дата", "модель", "схема", "ступень", "балл", "секунд",
        "вызовов", "заметка")


def мигрировать() -> None:
    """Добавить колонку «схема» в журнал, если её там ещё нет.

    Прежним строкам ставится `ru`: до 01.10.2026 другой схемы не было,
    так что это факт, а не допущение.
    """
    if not РЕЗУЛЬТАТЫ.is_file():
        return
    строки = [с for с in РЕЗУЛЬТАТЫ.read_text(encoding="utf-8").splitlines()
              if с.strip()]
    if not строки:
        return
    шапка = строки[0].split("\t")
    if "схема" in шапка:
        return

    где = шапка.index("модель") + 1 if "модель" in шапка else 1
    новые = ["\t".join(ПОЛЯ)]
    for с in строки[1:]:
        поля = с.split("\t")
        поля.insert(где, "ru")
        новые.append("\t".join(поля))
    # 🔴 Через временный файл и atomic replace (ревью 01.10.2026). Журнал —
    # единственная копия замеров, и восстанавливать его уже приходилось
    # из логов. Прерывание посреди `write_text` уничтожило бы историю;
    # `replace` либо проходит целиком, либо не меняет ничего.
    временный = РЕЗУЛЬТАТЫ.with_suffix(РЕЗУЛЬТАТЫ.suffix + ".tmp")
    временный.write_text("\n".join(новые) + "\n", encoding="utf-8")
    временный.replace(РЕЗУЛЬТАТЫ)
    print(f"🟡 журнал перенесён на колонку «схема»: строк {len(новые) - 1} → ru")


def _в_ячейку(значение: object) -> str:
    """Обезвредить значение для TSV: табы И переводы строки.

    🔴 Ревью 01.10.2026: заменялись только табы. Ключ аргумента подставляется
    в заметку как есть — ровно ради искажённых ключей (`пун` вместо `путь`)
    этот код и добавлен, — и ключ с переводом строки разорвал бы строку
    журнала на две. Тогда `--show` падает с KeyError на коротком ряду:
    стенд, ловящий искажения модели, ломался бы об искажение модели.
    """
    return str(значение).replace("\t", " ").replace("\r", " ").replace("\n", " ")


def дописать(строки: list[dict]) -> None:
    """Дописать строки прогона, при необходимости перенеся журнал.

    🔴 Шапка ставится по НЕПУСТОТЕ файла, а не по его существованию
    (ревью 01.10.2026). Пустой файл на нуле байт существует, `мигрировать`
    из него выходит сразу, и строки дописывались бы без шапки — а тогда
    `--show` принял бы первую строку данных за заголовок.
    """
    мигрировать()
    пусто = (not РЕЗУЛЬТАТЫ.is_file()) or РЕЗУЛЬТАТЫ.stat().st_size == 0
    with РЕЗУЛЬТАТЫ.open("a", encoding="utf-8") as ф:
        if пусто:
            ф.write("\t".join(ПОЛЯ) + "\n")
        for с in строки:
            ф.write("\t".join(_в_ячейку(с.get(п, "")) for п in ПОЛЯ) + "\n")


def показать() -> int:
    """Напечатать последний прогон каждой модели ПО КАЖДОЙ схеме.

    🔴 Схема входит в ключ группировки. Иначе прогон на латинице затёр бы
    кириллический — а именно их сравнение и есть предмет замера 01.10.2026.
    """
    if not РЕЗУЛЬТАТЫ.is_file():
        print("🟡 результатов нет")
        return 1
    строки = [с.split("\t") for с in
              РЕЗУЛЬТАТЫ.read_text(encoding="utf-8").splitlines() if с.strip()]
    данные = [dict(zip(строки[0], с)) for с in строки[1:]]
    веса = {з["имя"]: з["вес"] for з in задачи(СХЕМЫ["en"])}

    последние: dict[tuple[str, str, str], dict] = {}
    for с in данные:
        последние[(с["модель"], с.get("схема") or "ru", с["ступень"])] = с

    по_моделям: dict[tuple[str, str], list[dict]] = {}
    for (м, сх, _), с in последние.items():
        по_моделям.setdefault((м, сх), []).append(с)

    for (модель, схема), прогоны in sorted(по_моделям.items()):
        взято = sum(веса.get(п["ступень"], 1) for п in прогоны if п["балл"] == "1")
        балл = взято * 100 // sum(веса.values())
        значок = "🟢" if балл >= 80 else "🟡" if балл >= 50 else "🔴"
        пометка = " 🔴 схема с кириллицей, см. рейтинг §7" if схема == "ru" else ""
        # 🔴 Балл всегда делится на полную сумму весов — значит неполный набор
        # ступеней даёт ЗАНИЖЕННОЕ число, которое выглядит как результат
        # (ревью 01.10.2026). Журнал правится руками и восстанавливался
        # из логов, так что случай не гипотетический: помечаем вслух.
        if len(прогоны) < len(веса):
            пометка += (f" ⚠️ ступеней {len(прогоны)} из {len(веса)}"
                        f" — балл занижен, не сравнивать")
        print(f"{значок} {модель} [{схема}]: {балл}/100 вызов инструментов{пометка}")
        for п in sorted(прогоны, key=lambda п: п["ступень"]):
            print(f"   {'🟢' if п['балл'] == '1' else '🔴'} {п['ступень']:14} "
                  f"{п['секунд']:>7} с  вызовов: {п['вызовов']:<2} {п['заметка'][:60]}")
    return 0


def описать_вызовы(список: list[tuple[str, dict]]) -> str:
    """Собрать заметку о вызовах С КЛЮЧАМИ аргументов, а не только значениями.

    🔴 Прежняя версия печатала `list(а.values())[0]` — одно значение без ключа.
    Из-за этого вызов с искажённым ключом (`пун` вместо `путь`) выглядел
    в журнале идентично верному, и причину нуля нельзя было увидеть,
    не переспросив модель. Разбор — рейтинг §7.
    """
    части = []
    for имя, арг in список:
        пары = ", ".join(f"{к}={v!r}" for к, v in (арг or {}).items())
        части.append(f"{имя}({пары})")
    return ", ".join(части)


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model")
    ap.add_argument("--timeout", type=int, default=600)
    ap.add_argument("--show", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    # 🔴 По умолчанию `en`. Замер 01.10.2026: кириллические имена аргументов
    # стоят ступени из трёх тем моделям, у которых русский не основной, —
    # то есть дефектная схема не может быть схемой по умолчанию. `ru`
    # оставлена, чтобы дефект воспроизводился запуском, а не пересказом.
    ap.add_argument("--schema", choices=sorted(СХЕМЫ) + ["оба"], default="en")
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    if a.show or not a.model:
        return показать()

    имена_схем = sorted(СХЕМЫ) if a.schema == "оба" else [a.schema]
    # 🔴 Журнал пополняется ПОСЛЕ КАЖДОЙ ступени, а не в конце прогона
    # (ревью 01.10.2026). При `--schema оба` это шесть запросов с таймаутом
    # до 600 с каждый — до часа работы. Прежняя версия держала всё в памяти
    # и дописывала одним вызовом в конце: любое прерывание уносило замер
    # целиком, и это уже случалось (коммит 5745492 — «замеры восстановлены
    # из лога»). Батч, переживающий обрыв, — то же правило, что у вахты.
    for имя_схемы in имена_схем:
        схема = СХЕМЫ[имя_схемы]
        for з in задачи(схема):
            print(f"── {a.model} [{имя_схемы}] · {з['имя']} ({з['что']})", flush=True)
            ответ, замер = спросить(a.model, з["сообщения"], a.timeout, схема)
            если_вызовы = вызовы(ответ)
            if "ошибка" in замер:
                балл, заметка = 0, замер["ошибка"]
            else:
                балл = int(bool(з["грейдер"](ответ, схема)))
                текст = (ответ.get("message", {}) or {}).get("content", "") or ""
                заметка = (описать_вызовы(если_вызовы) if если_вызовы
                           else f"вызова нет: {' '.join(текст.split())[:80]}")
            print(f"   {'🟢' if балл else '🔴'} {замер['секунд']} с · {заметка[:100]}",
                  flush=True)
            дописать([{"дата": dt.date.today().isoformat(), "модель": a.model,
                       "схема": имя_схемы, "ступень": з["имя"], "балл": балл,
                       "секунд": замер["секунд"], "вызовов": len(если_вызовы),
                       "заметка": заметка[:120]}])
    return 0


if __name__ == "__main__":
    sys.exit(main())
