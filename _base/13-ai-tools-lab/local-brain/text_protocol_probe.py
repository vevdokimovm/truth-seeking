"""text_protocol_probe.py — берёт ли модель цепочку БЕЗ нативных вызовов.

🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ СТЕНД. `tool_probe.py` меряет нативный вызов инструментов
(поле `tool_calls` в ответе). Замеры 30.09–01.10.2026: одиночный вызов берут
четыре локальные модели из пяти, **цепочку — ни одна**, и `phi4-mini` не даёт
нативных вызовов вовсе, описывая их прозой.

Отсюда гипотеза, записанная в рейтинге §6: барьер не в способности выбрать
следующий шаг, а в **канале** — в требовании оформить его служебной
структурой. Оболочки вида `mini-swe-agent` этого требования не предъявляют:
у них один инструмент `bash`, а действие разбирается из ТЕКСТА ответа.
Если гипотеза верна, та же модель, легшая на цепочке в `tool_probe.py`,
должна пройти её здесь.

🔴 ПОЧЕМУ НЕ САМ `mini-swe-agent`. Он исполняет команды, которые модель
сочинила, в настоящей оболочке на рабочей машине. Для замера способности
это не нужно, а необратимость вносит: достаточно проверить, выдаёт ли модель
разбираемое действие и верно ли выбирает СЛЕДУЮЩЕЕ после результата.
Поэтому здесь вывод «инструмента» подставляется стендом, а команды модели
**никогда не исполняются** — ни одна строка из её ответа не попадает
в оболочку. Это замер протокола, не прогон агента.

🔴 ЧЕГО ЭТОТ СТЕНД НЕ МЕРИТ:
  · исполнимость команды — она не запускается, проверяется только форма
    и адресат (какой файл модель собирается читать);
  · длинный контекст: истории здесь три сообщения, не тысячи токенов;
  · устойчивость: один прогон на ступень;
  · настоящий `mini-swe-agent` целиком — его промпт, ретраи и разбор
    отличаются, и совпадение вывода здесь не гарантирует совпадения там.

ЗАПУСК
    text_protocol_probe.py --model phi4-mini:latest
    text_protocol_probe.py --show
    text_protocol_probe.py --selftest
"""
