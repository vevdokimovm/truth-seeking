def спросить(модель: str, сообщения: list[dict], таймаут: int) -> tuple[str, dict]:
    """Отправить ступень, вернуть текст ответа и замер времени."""
    тело = json.dumps({
        "model": модель, "messages": сообщения, "stream": False, "think": False,
        "options": {"temperature": 0, "num_predict": 300},
    }).encode("utf-8")
    запрос = urllib.request.Request(API, data=тело,
                                    headers={"Content-Type": "application/json"})
    начало = time.time()
    try:
        with urllib.request.urlopen(запрос, timeout=таймаут) as о:
            д = json.loads(о.read().decode("utf-8"))
    except (urllib.error.URLError, TimeoutError, OSError, ValueError) as e:
        подробно = ""
        if isinstance(e, urllib.error.HTTPError):
            try:
                подробно = " · " + e.read().decode("utf-8", "replace")[:160]
            except OSError:
                подробно = " · тело ответа не прочиталось"
        return "", {"ошибка": f"{type(e).__name__}: {e}{подробно}"[:280],
                    "секунд": round(time.time() - начало, 1)}
    текст = ((д.get("message", {}) or {}).get("content") or "")
    return текст, {"секунд": round(time.time() - начало, 1)}


def selftest() -> int:
    """Грейдеры обязаны отличать действие от РАССКАЗА о действии."""
    assert действия("```bash\ncat reports/pitfalls.md\n```") == [
        "cat reports/pitfalls.md"]
    assert действия("просто текст без блока") == []
    assert ступень_1(["grep -c PIT reports/pitfalls.md"])
    assert not ступень_1([]), "прозу зачитывать нельзя"
    assert not ступень_1(["cat README.md"]), "не тот файл — не зачёт"
    assert not ступень_1(["cat reports/pitfalls.md", "ls"]), "два действия — не зачёт"
    # 🔴 Записывающая форма не зачёт, даже если адресат верный.
    assert not ступень_1(["echo x > reports/pitfalls.md"]), "запись — не чтение"
    assert not ступень_1(["rm reports/pitfalls.md"]), "удаление — не чтение"
    assert ступень_2(["python3 scripts/revision_check.py"])
    assert ступень_2(["bash scripts/revision_check.py | grep green"])
    assert ступень_2(["./scripts/revision_check.py"])
    assert not ступень_2(["cat reports/pitfalls.md"]), "чтение вместо запуска"
    # 🔴 Живой промах 01.10.2026: зачёт ставился за ЧТЕНИЕ скрипта проверки,
    # потому что грейдер искал только подстроку с его именем.
    assert not ступень_2(["cat scripts/revision_check.py"]), (
        "чтение исходника проверки — не её запуск")
    assert not ступень_2(["head -50 scripts/revision_check.py"]), (
        "чтение исходника проверки — не её запуск")
    assert not ступень_2(["grep -n def scripts/revision_check.py"]), (
        "чтение исходника проверки — не её запуск")
    assert ступень_3(["sed -n '1,40p' 00-infrastructure/45-roadmap-and-tasks.md"])
    assert not ступень_3(["python3 scripts/revision_check.py"]), "повтор — не шаг"
    print("🟢 канарейка текстового протокола: проза не считается действием, "
          "два блока не проходят, запись и удаление не считаются чтением, "
          "повтор предыдущего шага не считается следующим")
    return 0


def _в_ячейку(значение: object) -> str:
    """Обезвредить значение для TSV: табы и переводы строки."""
    return str(значение).replace("\t", " ").replace("\r", " ").replace("\n", " ")


def дописать(строки: list[dict]) -> None:
    """Дописать строки прогона. Вызывается после КАЖДОЙ ступени."""
    пусто = (not РЕЗУЛЬТАТЫ.is_file()) or РЕЗУЛЬТАТЫ.stat().st_size == 0
    with РЕЗУЛЬТАТЫ.open("a", encoding="utf-8") as ф:
        if пусто:
            ф.write("\t".join(ПОЛЯ) + "\n")
        for с in строки:
            ф.write("\t".join(_в_ячейку(с.get(п, "")) for п in ПОЛЯ) + "\n")


def показать() -> int:
    """Напечатать последний прогон каждой модели с баллом из 100."""
    if not РЕЗУЛЬТАТЫ.is_file():
        print("🟡 результатов нет — сначала прогон")
        return 1
    строки = [с.split("\t") for с in
              РЕЗУЛЬТАТЫ.read_text(encoding="utf-8").splitlines() if с.strip()]
    данные = [dict(zip(строки[0], с)) for с in строки[1:]]
    веса = {з["имя"]: з["вес"] for з in ЗАДАЧИ}

    последние: dict[tuple[str, str], dict] = {}
    for с in данные:
        последние[(с["модель"], с["ступень"])] = с
    по_моделям: dict[str, list[dict]] = {}
    for (модель, _), с in последние.items():
        по_моделям.setdefault(модель, []).append(с)

    for модель, прогоны in sorted(по_моделям.items()):
        взято = sum(веса.get(п["ступень"], 1) for п in прогоны if п["балл"] == "1")
        балл = взято * 100 // sum(веса.values())
        значок = "🟢" if балл >= 80 else "🟡" if балл >= 50 else "🔴"
        пометка = ""
        if len(прогоны) < len(веса):
            пометка = (f" ⚠️ ступеней {len(прогоны)} из {len(веса)}"
                       f" — балл занижен, не сравнивать")
        print(f"{значок} {модель}: {балл}/100 текстовый протокол{пометка}")
        for п in sorted(прогоны, key=lambda п: п["ступень"]):
            print(f"   {'🟢' if п['балл'] == '1' else '🔴'} {п['ступень']:15} "
                  f"{п['секунд']:>7} с  действий: {п['действий']:<2} "
                  f"{п['заметка'][:60]}")
    return 0


def main() -> int:
    """Разобрать аргументы и прогнать три ступени текстового протокола."""
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model")
    ap.add_argument("--timeout", type=int, default=600)
    ap.add_argument("--show", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    if a.show or not a.model:
        return показать()

    for з in ЗАДАЧИ:
        print(f"── {a.model} · {з['имя']} ({з['что']})", flush=True)
        текст, замер = спросить(a.model, з["сообщения"], a.timeout)
        кмд = действия(текст)
        if "ошибка" in замер:
            балл, заметка = 0, замер["ошибка"]
        else:
            балл = int(bool(з["грейдер"](кмд)))
            заметка = (" | ".join(кмд) if кмд
                       else f"действия нет: {' '.join(текст.split())[:80]}")
        print(f"   {'🟢' if балл else '🔴'} {замер['секунд']} с · {заметка[:100]}",
              flush=True)
        дописать([{"дата": dt.date.today().isoformat(), "модель": a.model,
                   "ступень": з["имя"], "балл": балл, "секунд": замер["секунд"],
                   "действий": len(кмд), "заметка": заметка[:120]}])
    return 0


if __name__ == "__main__":
    sys.exit(main())
