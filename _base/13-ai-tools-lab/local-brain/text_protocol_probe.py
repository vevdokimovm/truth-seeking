БЛОК = re.compile(r"```(?:bash|sh|shell)?\s*\n(.*?)```", re.S)


def действия(ответ: str) -> list[str]:
    """Команды из блоков кода ответа. Пусто — модель не дала действия."""
    return [к.strip() for к in БЛОК.findall(ответ or "") if к.strip()]


def ступень_1(кмд: list[str]) -> bool:
    """Одно действие, читающее именно тот файл, о котором спросили."""
    if len(кмд) != 1:
        return False
    к = кмд[0]
    return "reports/pitfalls.md" in к and _читает(к)


def ступень_2(кмд: list[str]) -> bool:
    """Выбор: ЗАПУСТИТЬ проверку, а не читать её исходник.

    🔴 Дефект найден живым прогоном 01.10.2026, на второй же модели.
    Первая редакция проверяла только подстроку `revision_check` — и
    `base-local` получила зачёт за `cat scripts/revision_check.py`, то есть
    за чтение скрипта вместо его запуска. Это ровно то различение, которое
    задача и заявляет, и грейдер его не делал: он спрашивал «упомянут ли
    скрипт», а не «запущен ли».

    Канарейка этого не поймала, потому что проверяла чтение ДРУГОГО файла
    (`cat reports/pitfalls.md`) — то есть случай, где подстрока отсутствует.
    Класс тот же, что у ключа `пун` в `tool_probe.py`: проверка смотрела
    на значение, а не на то, что требуется.
    """
    if len(кмд) != 1:
        return False
    к = кмд[0]
    if "revision_check" not in к:
        return False
    # 🔴 Достаточно признака ЗАПУСКА, и добавлять «не читает» нельзя.
    # Канарейка поймала это сразу: `bash scripts/revision_check.py | grep green`
    # — законный запуск с фильтром вывода, но `grep` в конвейере попадает
    # под признак чтения, и зачёт терялся. Чтение исходника отсекается само:
    # `cat scripts/revision_check.py` не начинается с формы запуска.
    return _запускает(к)


def _запускает(команда: str) -> bool:
    """Похоже ли, что команда ИСПОЛНЯЕТ скрипт, а не открывает его."""
    низ = команда.strip().lower()
    формы = ("python3 ", "python ", "bash ", "sh ", "./", "make ", "uv run ")
    return any(низ.startswith(ф) or f"&& {ф}" in низ or f"| {ф}" in низ
               for ф in формы)


def ступень_3(кмд: list[str]) -> bool:
    """Цепочка: открыть ИМЕННО тот файл, который назван в падении."""
    if len(кмд) != 1:
        return False
    к = кмд[0]
    return "45-roadmap-and-tasks.md" in к and _читает(к)


def _читает(команда: str) -> bool:
    """Похоже ли, что команда читает файл, а не пишет в него.

    🔴 Записывающую команду считать зачётом нельзя: стенд меряет выбор
    следующего шага, и «открыть файл» с «перезаписать файл» — разные шаги.
    Исполнение здесь не происходит, но и зачёт за разрушительную форму
    ставить не за что.
    """
    низ = команда.lower()
    пишет = (">", ">>", "rm ", "mv ", "sed -i", "tee ", "truncate")
    if any(п in низ for п in пишет):
        return False
    читает = ("cat ", "head ", "tail ", "less ", "grep ", "sed -n", "awk ",
              "wc ", "nl ", "open ", "python3 -c")
    return any(ч in низ for ч in читает)


